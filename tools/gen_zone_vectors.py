#!/usr/bin/env python3
"""Generate src/tests/vectors_zone.h: the zone overlap test of the original (1000:2022 .. 2108: a thing's box against up to four zone boxes of its room, raising event 10 for each
overlap), run for random boxes in the Unicorn harness; checked by test_formats against main.c's rule (engine/collision.c zone_overlap)."""
import sys, os, struct, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu_call import *
from unicorn import *

e = boot(1)
QB, ROOMREC, BLK = 0x7800, 0x7900, 0x7A00
random.seed(11)
rows = []
for n in range(400):
    s8 = lambda: random.randint(-20, 80)
    zones = []
    for b in range(4):
        x0, y0 = s8(), s8(); x1, y1 = x0 + random.randint(0, 40), y0 + random.randint(0, 40)
        z0 = random.randint(-5, 30); z1 = z0 + random.randint(0, 20)
        zones.append((x0, y0, x1, y1, z0, z1))
    tx0, ty0 = s8(), s8(); tx1, ty1 = tx0 + random.randint(0, 30), ty0 + random.randint(0, 30)
    tzb = random.randint(-5, 30); tzt = tzb + random.randint(0, 40)
    blk = b''.join(struct.pack('6b', *z) for z in zones)
    e.wr(0x1F17, BLK, blk)
    e.wr(0x1F17, ROOMREC, bytes(0x20))                     # room record with byte 17h = 0: no room events
    e.wr(0x1F17, 0x84, struct.pack('<H', QB))
    e.wr(0x1F17, 0x226, struct.pack('<H', 0))
    e.wr(0x1F17, 0x5BC, struct.pack('<H', 0x1234))
    r = call(e, 0x2022, esi=BLK, ebp=ROOMREC, edx=((ty1 & 0xFF) << 8) | (tx1 & 0xFF), ecx=((tzb & 0xFF) << 8) | (tx0 & 0xFF), ebx=((tzt & 0xFF) << 8) | (ty0 & 0xFF), es=0x1F17, ds=0x1F17)
    cnt = struct.unpack('<H', e.rd(0x1F17, 0x226, 2))[0]
    mask = 0
    for k in range(cnt):
        t, obj, arg = struct.unpack('<HHH', e.rd(0x1F17, QB + 6 * k, 6))
        assert t == 0x0A, t
        mask |= 1 << (arg - 1)
    rows.append((tx1, ty1, tx0, ty0, tzt, tzb, mask) + tuple(v for z in zones for v in z))
with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'tests', 'vectors_zone.h'), 'w') as f:
    f.write('/* generated by tools/gen_zone_vectors.py from the original 1000:2018 (thing box x1 y1 x0 y0 zt zb, overlap mask over boxes 1..4, then the four boxes x0 y0 x1 y1 z0 z1) */\nstatic const int zone_vectors[][31] = {\n')
    for r in rows:
        f.write('\t{%s},\n' % ', '.join(str(v) for v in r))
    f.write('};\n#define N_ZONE_VECTORS %d\n' % len(rows))
print(len(rows), 'vectors; masks seen', sorted({r[6] for r in rows}))
