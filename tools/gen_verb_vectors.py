#!/usr/bin/env python3
"""Generate src/tests/vectors_verbs.h: the verb list of a carried thing (1000:12C72) for real level 1..3 things as the carried item and as the touched thing ahead, run in the
Unicorn harness; checked by test_formats against engine/panel.c carried_verbs_list."""
import sys, os, struct, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu_call import *

random.seed(9)
rows = []
for level in (1, 2, 3):
    e = boot(level)
    def rec(t):
        r = call(e, 0x407F, edx=t, eax=0, es=0x1F17, ds=0x1F17)
        return None if r['eflags'] & 0x40 else r['edi'] & 0xFFFF
    def hdr(t):
        d = rec(t)
        w = struct.unpack('<H', e.rd(0x1F17, d + 6, 2))[0]
        r = call(e, 0x410E, eax=2, edx=w, es=0x1F17, ds=0x1F17)
        return r['es'], r['edi'] & 0xFFFF
    things = []
    for t in range(1, 1000):
        try:
            d = rec(t)
            if d is None: continue
            s, o = hdr(t)
            h = bytes(e.rd(s, o, 0x30))
            a = e.rd(0x1F17, d + e.rd(0x1F17, d + 12, 1)[0], 8)
            things.append((t, h, bytes(a), e.rd(0x1F17, d + 15, 1)[0]))
        except Exception:
            continue
    print('level', level, len(things), 'things')
    for n in range(200):
        c = random.choice(things); tg = random.choice(things + [None, None])
        e.wr(0x1F17, 0x260, c[0].to_bytes(2, 'little'))
        e.wr(0x1F17, 0x58C, (tg[0] if tg else 0).to_bytes(2, 'little'))
        if tg: e.wr(0x1F17, 0x6D3, bytes([tg[1][0x16]]))
        # the original reads the item's header 16h / 17h / 1Dh, its record byte 15 and A[7], the target's class and A[4]
        try:
            call(e, 0x2C72, es=0x1F17, ds=0x1F17)
        except Exception:
            continue
        out = []; p = 0xFDC2
        while len(out) < 12:
            b = e.rd(0x1F17, p, 1)[0]
            if b == 0xFF: break
            out.append(b); p += 1
        rows.append((c[1][0x16], c[1][0x17], c[1][0x1D], 1 if c[3] & 0x40 else 0, c[2][7], (tg[1][0x16] if tg else -1), (tg[2][4] if tg else 0), len(out)) + tuple(out) + (0,) * (10 - len(out)))
with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'tests', 'vectors_verbs.h'), 'w') as f:
    f.write('/* generated by tools/gen_carried_verb_vectors.py from the original 1000:12C72: item h16 h17 h1D, rec[15]&40, A[7], touched class (-1 none), its A[4], count, verbs */\nstatic const int verb_vectors[][18] = {\n')
    for r in rows:
        f.write('\t{%s},\n' % ', '.join(str(v) for v in r))
    f.write('};\n#define N_CARRIED_VERB_VECTORS %d\n' % len(rows))
print(len(rows), 'vectors')
