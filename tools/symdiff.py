#!/usr/bin/env python3
"""Lists, symbol by symbol, what two builds of the engine (ELF files with a full .symtab, e.g. Deponia and Deponia4) do and do not share.
Usage: tools/symdiff.py <first> <second> [-o out.md]   (needs nm and c++filt on the PATH, e.g. /c/mingw64/bin)

The output is a markdown file with, for the second build compared with the first:
  - the libraries that are linked in (by the prefix of their symbols) that only one has: a different set of libraries is a
    different build, not a different game
  - the classes of the engine (T*, and the other classes that the builds have in common with a T* class around them) that only
    one has, with all their methods
  - the methods that one has and the other has not, class by class (compiler clones such as `[clone .part.N]` are left out: they
    are the optimizer's, not the source's)
  - the free functions and the global variables of the engine that only one has
The symbols that both define are not listed here: tools/crosscompare.py says how much their code differs."""
import re
import subprocess
import sys
from collections import defaultdict

LIBRARIES = [
    ("HarfBuzz", r"^(hb_|OT::|GSUBProxy|GPOSProxy|IItem)"),
    ("FreeType", r"^(FT_|ft_|tt_|cff_|af_|ps_|t1_|sfnt_|pcf_|bdf_|pfr_|psaux|psh)"),
    ("Box2D", r"^(b2|tolua_.*b2)"),
    ("Assimp", r"^(ai[A-Z]|Assimp)"),
    ("glm", r"^glm::"),
    ("Lua / tolua", r"^(lua|tolua|luaL|Lutf8|Lutf8_)"),
    ("wxWidgets", r"^(wx|WX)"),
    ("SDL2", r"^SDL_"),
    ("libpng / zlib", r"^(png_|inflate|deflate|crc32|adler32|gz)"),
    ("Spine", r"^(sp[A-Z]|_sp)"),
    ("Steam", r"^(CSteam|SteamAPI|Steam)"),
    ("Galaxy (GOG)", r"galaxy|Galaxy"),
    ("sqlite", r"^sqlite3"),
    ("curl", r"^curl_"),
    ("libwebp / vpx / opus", r"^(WebP|vp8|vp9|vpx|opus|ogg|vorbis)"),
]
STD = re.compile(r"^(std::|__gnu_cxx::|__cxxabiv1::|__cxa_|__gxx|operator |_GLOBAL__|\(anonymous namespace\)::_|typeinfo|vtable|guard variable|VTT|non-virtual thunk|virtual thunk|construction vtable|covariant return|reference temporary|transaction clone|_Z|_IO_|_fini|_init|__[a-z]|\.)")
CLONE = re.compile(r"\[clone \.[A-Za-z]+\.?\d*\]")


def load(path):
    out = subprocess.run(["nm", "-S", "--defined-only", path], capture_output=True, text=True, check=True).stdout
    names = []
    kinds = {}
    for line in out.splitlines():
        parts = line.split(" ", 3)
        if len(parts) == 4:
            names.append(parts[3])
            kinds[parts[3]] = parts[2]
        elif len(parts) == 3:
            names.append(parts[2])
            kinds[parts[2]] = parts[1]
    dem = subprocess.run(["c++filt"], input="\n".join(names), capture_output=True, text=True, check=True).stdout.splitlines()
    return {d: kinds[n] for n, d in zip(names, dem)}


def strip_prefixes(name):
    return re.sub(r"^(non-virtual thunk to |virtual thunk to |vtable for |typeinfo for |typeinfo name for |guard variable for |VTT for )", "", name)


def owner(name):
    m = re.match(r"^(T[A-Za-z0-9_]*)::", strip_prefixes(name))
    return m.group(1) if m else None


def library(name):
    base = strip_prefixes(name)
    for lib, rx in LIBRARIES:
        if re.search(rx, base):
            return lib
    return None


def main():
    args = sys.argv[1:]
    out = None
    if "-o" in args:
        i = args.index("-o")
        out = args[i + 1]
        del args[i:i + 2]
    if len(args) != 2:
        print(__doc__)
        return 1
    s1, s2 = load(args[0]), load(args[1])
    n1, n2 = args[0].replace("\\", "/").split("/")[-1], args[1].replace("\\", "/").split("/")[-1]
    lines = []
    w = lines.append
    w("# Symbols of %s compared with %s" % (n2, n1))
    w("")
    w("Generated by `tools/symdiff.py`. `+` means that %s has it and %s has not, `-` the other way round. Compiler clones are left out." % (n2, n1))
    w("")

    w("## Libraries (symbols per library: %s / %s)" % (n1, n2))
    w("")
    w("| Library | %s | %s |" % (n1, n2))
    w("|---|---|---|")
    counts = defaultdict(lambda: [0, 0])
    for i, s in enumerate((s1, s2)):
        for n in s:
            lib = library(n)
            if lib:
                counts[lib][i] += 1
    for lib, (a, b) in sorted(counts.items()):
        w("| %s | %d | %d |" % (lib, a, b))
    w("")

    only1 = {n for n in s1 if n not in s2 and not CLONE.search(n)}
    only2 = {n for n in s2 if n not in s1 and not CLONE.search(n)}

    c1 = {owner(n) for n in s1} - {None}
    c2 = {owner(n) for n in s2} - {None}
    w("## Classes only in %s (%d)" % (n2, len(c2 - c1)))
    w("")
    for c in sorted(c2 - c1):
        methods = sorted(n for n in only2 if owner(n) == c and not STD.match(strip_prefixes(n)) or (owner(n) == c and "::" in n))
        w("### `%s` (%d symbols)" % (c, len(methods)))
        w("")
        for n in methods:
            w("- `%s`" % n)
        w("")
    w("## Classes only in %s (%d)" % (n1, len(c1 - c2)))
    w("")
    for c in sorted(c1 - c2):
        w("- `%s`" % c)
    w("")

    w("## Methods of classes both builds have")
    w("")
    for sign, only, label in (("+", only2, n2), ("-", only1, n1)):
        by_class = defaultdict(list)
        for n in only:
            c = owner(n)
            if c and c in c1 & c2 and not n.startswith(("vtable", "typeinfo", "VTT")):
                # templates of the library instantiated inside a method of the class are noise: keep the class's own methods
                if re.match(r"^(non-virtual thunk to |virtual thunk to )?" + re.escape(c) + r"::", n):
                    by_class[c].append(n)
        w("### Only in %s (%s)" % (label, sign))
        w("")
        for c in sorted(by_class):
            w("**%s** (%d)" % (c, len(by_class[c])))
            w("")
            for n in sorted(by_class[c]):
                w("- `%s`" % n)
            w("")

    w("## Free functions and globals of the engine only in one build")
    w("")
    for sign, only, label in (("+", only2, n2), ("-", only1, n1)):
        items = []
        for n in sorted(only):
            if owner(n) or library(n) or STD.match(strip_prefixes(n)):
                continue
            if "::" in n.split("(")[0]:
                continue
            items.append(n)
        w("### Only in %s (%s, %d)" % (label, sign, len(items)))
        w("")
        for n in items:
            w("- `%s`" % n)
        w("")

    text = "\n".join(lines) + "\n"
    if out:
        with open(out, "w", encoding="utf8", newline="\n") as f:
            f.write(text)
        print("wrote %s (%d lines)" % (out, len(lines)))
    else:
        sys.stdout.write(text)
    return 0


sys.exit(main())
