#!/usr/bin/env python3
"""Turns the table of tools/crosscompare.py (build/cross/<game>[-tag]-compare.tsv) into a markdown report: per class of the engine,
how many functions the reconstruction has in common with the original, how many of them are unlike (score under --limit), and
the least alike ones with the sizes (instructions in the original / in the reconstruction).
Usage: tools/crossreport.py <compare.tsv> [-o report.md] [--limit 0.5] [--per-class 12]   (needs c++filt on the PATH)"""
import collections
import re
import subprocess
import sys


def demangle(names):
    out = subprocess.run(["c++filt"], input="\n".join(names), capture_output=True, text=True, check=True).stdout.splitlines()
    return dict(zip(names, out))


def klass(mangled):
    m = re.match(r"_ZN[K]?(\d+)(.*)", mangled)
    if m:
        return m.group(2)[:int(m.group(1))]
    return None


def main():
    args = sys.argv[1:]
    out = None
    limit = 0.5
    per_class = 12
    pos = []
    i = 0
    while i < len(args):
        if args[i] == "-o":
            out = args[i + 1]
            i += 1
        elif args[i] == "--limit":
            limit = float(args[i + 1])
            i += 1
        elif args[i] == "--per-class":
            per_class = int(args[i + 1])
            i += 1
        else:
            pos.append(args[i])
        i += 1
    if len(pos) != 1:
        print(__doc__)
        return 1
    rows = []
    with open(pos[0]) as f:
        next(f)
        for line in f:
            p = line.rstrip("\n").split("\t")
            rows.append((p[0], float(p[1]), int(p[6]), int(p[7])))
    names = demangle([r[0] for r in rows])
    by = collections.defaultdict(list)
    free = []
    for r in rows:
        c = klass(r[0])
        if c and c.startswith("T") or c in ("Tween", "TextBox", "Tooltip", "TooltipHolder", "ParticleContainer", "GLCharBuffer"):
            by[c].append(r)
        elif not c:
            free.append(r)
    lines = ["# Functions that differ most from the original (%s)" % pos[0].replace("\\", "/").split("/")[-1], "",
             "Generated by `tools/crossreport.py` from the table of `tools/crosscompare.py`. Score 1.0 is the same calls, numbers, texts and",
             "shape; 'unlike' is a score under %.2f. The instruction counts are original / reconstruction." % limit, "",
             "| Class | in both | unlike | mean score (by size) |", "|---|---|---|---|"]
    table = []
    for c, rs in by.items():
        total = sum(r[2] for r in rs) or 1
        table.append((c, len(rs), sum(1 for r in rs if r[1] < limit), sum(r[1] * r[2] for r in rs) / total))
    for c, n, u, m in sorted(table, key=lambda t: (-t[2], t[0])):
        if u:
            lines.append("| %s | %d | %d | %.2f |" % (c, n, u, m))
    lines.append("")
    for c, n, u, m in sorted(table, key=lambda t: (-t[2], t[0])):
        if not u:
            continue
        lines.append("## %s (%d of %d unlike)" % (c, u, n))
        lines.append("")
        for name, score, a, b in sorted(by[c], key=lambda r: (r[1], -r[2]))[:min(per_class, u)]:
            lines.append("- %.2f  %d / %d  `%s`" % (score, a, b, names[name]))
        lines.append("")
    lines.append("## Free functions (%d unlike of %d)" % (sum(1 for r in free if r[1] < limit), len(free)))
    lines.append("")
    for name, score, a, b in sorted(free, key=lambda r: (r[1], -r[2]))[:40]:
        if score < limit:
            lines.append("- %.2f  %d / %d  `%s`" % (score, a, b, names[name]))
    text = "\n".join(lines) + "\n"
    if out:
        with open(out, "w", encoding="utf8", newline="\n") as f:
            f.write(text)
        print("wrote %s (%d lines)" % (out, len(lines)))
    else:
        sys.stdout.write(text)
    return 0


sys.exit(main())
