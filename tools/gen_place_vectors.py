#!/usr/bin/env python3
"""Generate src/tests/vectors_place.h: the spot 1000:6C72 computes for a dropped / thrown thing, for random player records (x1, y1, x0, y0), thing boxes (xs, ys) and
the eight facings, obtained by running the ORIGINAL routine in the Unicorn harness (tools/emu_call.py); checked by test_formats against engine/collision.c place_spot."""
import sys, os, struct, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu_call import *
from unicorn import *

e = boot(1)
HDR, REC = 0x7100, 0x7300
stop = e.lin(0x1000, 0x6D33)
random.seed(7)
rows = []
for n in range(60):
    x1, y1 = random.randint(30, 90), random.randint(30, 90)
    x0, y0 = x1 - random.randint(5, 8), y1 - random.randint(5, 8)
    xs, ys = random.randint(1, 8), random.randint(1, 8)
    h = bytearray(0x30); h[0x10] = xs; h[0x12] = ys
    e.wr(0x1F17, HDR, bytes(h))
    e.wr(0x1F17, REC, bytes([x1, y1, x0, y0, 0, 0, 0, 0]))
    for face in (1, 2, 4, 8, 9, 5, 6, 10):
        saved = {r: e.r(r) for r in REGS}
        sp = e.r('sp') - 2
        e.wr(e.r('ss'), sp, struct.pack('<H', 0xFFF0)); e.w('sp', sp)
        for k, v in dict(ebp=REC, esi=0x7400, edi=HDR, es=0x1F17, ds=0x1F17, eax=face << 8, ecx=0, ebx=0).items():
            e.w(k, v)
        e.uc.emu_start(e.lin(0x1000, 0x6C72), stop, count=5000)
        dx = e.r('edx')
        for r, v in saved.items():
            e.w(r, v)
        rows.append((face, x1, y1, x0, y0, xs, ys, dx & 0xFF, (dx >> 8) & 0xFF))
with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'tests', 'vectors_place.h'), 'w') as f:
    f.write('/* generated by tools/gen_place_vectors.py from the original 1000:6C72 */\nstatic const int place_vectors[][9] = {\n')
    for r in rows:
        f.write('\t{%s},\n' % ', '.join(str(v) for v in r))
    f.write('};\n#define N_PLACE_VECTORS %d\n' % len(rows))
print(len(rows), 'vectors')
