#!/usr/bin/env python3
"""Generate src/tests/vectors_beeper.h: for sound ids 0..0x45 the sequence of PIT divisors the Beeper driver sounds (play, 150 ticks, stop at tick 70) and a
few combined scenarios; checked by test_formats against the C port (src/engine/beeper.c)."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import beeper

root = beeper.ROOT


def fnv(vals):
    h = 0x811C9DC5
    for v in vals:
        for b in (v & 0xFF, v >> 8 & 0xFF):
            h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def divs(b, n):
    out = []
    for _ in range(n):
        f = b.tick()
        out.append(round(1193182 / f) if f else 0)
    return out


rows = []
for sid in range(0, 0x46):
    b = beeper.Beeper()
    seq = []
    b.play(sid)
    seq += divs(b, 70)
    b.stop(sid)
    seq += divs(b, 80)
    rows.append(('single', sid, 0, fnv(seq), sum(1 for x in seq if x)))
scen = [
    [('play', 1), ('t', 30), ('play', 12), ('t', 40), ('play', 7), ('t', 40), ('stop', 11), ('t', 60)],
    [('play', 34), ('t', 20), ('play', 2), ('t', 60), ('stop', 1), ('t', 20), ('play', 5), ('t', 30)],
    [('play', 0x0b), ('t', 10), ('play', 0x0c), ('t', 10), ('play', 0x1d), ('t', 100), ('stop', 0x0b), ('t', 30), ('stop', 0x1d), ('t', 50)],
    [('music', 1), ('t', 400), ('music', 1), ('t', 400), ('music', 0), ('t', 60)],
]
for k, sc in enumerate(scen):
    b = beeper.Beeper()
    seq = []
    for op, v in sc:
        if op == 'play':
            b.play(v)
        elif op == 'stop':
            b.stop(v)
        elif op == 'music':
            b.music(v)
        else:
            seq += divs(b, v)
    rows.append(('scenario', k, 0, fnv(seq), sum(1 for x in seq if x)))
with open(os.path.join(root, 'src', 'tests', 'vectors_beeper.h'), 'w') as o:
    o.write('/* generated by tools/gen_beeper_vectors.py - do not edit */\n')
    o.write('typedef struct { int kind; int id; unsigned hash; int sounding; } BeeperVector;  /* kind 0 = single sound id, 1 = scenario id */\n')
    o.write('static const BeeperVector beeper_vectors[] = {\n')
    for kind, i, _, h, n in rows:
        o.write('\t{%d, %d, 0x%08XU, %d},\n' % (0 if kind == 'single' else 1, i, h, n))
    o.write('};\n')
print(len(rows), 'beeper vectors')
