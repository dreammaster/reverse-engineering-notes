#!/usr/bin/env python3
"""Generate src/tests/vectors_describe.h: the class-specific look text of the original (1000:84D9) for random spell / potion / weapon / ammunition structs, level 1,
English; checked by test_formats against engine/describe.c item_description."""
import sys, os, struct, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu_call import *

e = boot(1)
HDR, AS, BUF = 0x7100, 0x7200, 0x7500
random.seed(3)
rows = []
def astruct(thing):
    r = call(e, 0x407F, edx=thing, eax=0, es=0x1F17, ds=0x1F17)
    di = r['edi'] & 0xFFFF
    return bytes(e.rd(0x1F17, di + e.rd(0x1F17, di + 12, 1)[0], 8))
for n in range(300):
    cls = random.choice([1, 1, 2, 2, 4, 0x80, 0x81, 0x82])
    a = bytearray(random.getrandbits(8) for _ in range(8))
    ammo = 0
    ammo_a = bytes(8)
    if cls == 1: a[0] = random.randint(0, 26)
    elif cls == 2: a[0] = random.randint(0, 17)
    if cls in (1, 2):
        a[3] = random.choice([0, 1, 4, 5, 2, 0x80, 0x81])
        a[2] = random.randint(0, 40); a[1] = random.randint(0, 255)
    if cls == 4:
        ammo = random.choice([27, 87, 121, 132])
        a[0], a[1], a[2] = ammo >> 8, ammo & 255, 0
        ammo_a = astruct(ammo)
    if cls & 0x80 and random.random() < 0.3: a[2] = 0xFF
    h = bytearray(0x30); h[0x16] = cls
    e.wr(0x1F17, HDR, bytes(h)); e.wr(0x1F17, AS, bytes(a)); e.wr(0x1F17, BUF, bytes(200))
    call(e, 0x84D9, ebp=HDR, edi=AS, esi=BUF, es=0x1F17, ds=0x1F17, ebx=0)
    txt = bytes(e.rd(0x1F17, BUF, 200)).split(b'\0')[0].decode()
    rows.append((cls, bytes(a), ammo_a, txt))
with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'tests', 'vectors_describe.h'), 'w') as f:
    f.write('/* generated by tools/gen_describe_vectors.py from the original 1000:84D9 (level 1, English): class, A[0..7], ammunition A[0..7], expected text */\n')
    f.write('typedef struct { int cls; uint8_t a[8], ammo[8]; const char *text; } DescribeVector;\nstatic const DescribeVector describe_vectors[] = {\n')
    for cls, a, am, t in rows:
        f.write('\t{%d, {%s}, {%s}, "%s"},\n' % (cls, ','.join(map(str, a)), ','.join(map(str, am)), t.replace('\\', '\\\\').replace('"', '\\"')))
    f.write('};\n#define N_DESCRIBE_VECTORS %d\n' % len(rows))
print(len(rows), 'vectors; sample:', rows[0][3], '|', rows[5][3])
