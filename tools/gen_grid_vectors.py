#!/usr/bin/env python3
"""Generate src/tests/vectors_grid.h: one cursor move of the whole-rucksack grid (1000:125CF, the key handling from 1000:2746 to 2825) for every rucksack size 1..32, the four
keys and many cursor states, run in the Unicorn harness; checked by test_formats against engine/ruckgrid.c."""
import sys, os, struct, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emu_call import *
from unicorn import *

e = boot(1)
stop = e.lin(0x1000, 0x2825)
random.seed(5)
rows = []
for n in range(1, 33):
    R = (n - 1) // 4 if n > 1 else 0
    C = (n - 1) % 4
    states = []
    for row in range(R + 1):
        for col in range((C if row == R else 3) + 1):
            for sc in range(0, max(0, R - 3) + 1):
                vis = row - sc
                if 0 <= vis <= min(R, 3):
                    states.append((col, row, vis, sc))
    random.shuffle(states)
    for (col, row, vis, sc) in states[:24]:
        for key in (1, 2, 4, 8):
            e.wr(0x1F17, 0x6AF, bytes([col])); e.wr(0x1F17, 0x6B0, bytes([row])); e.wr(0x1F17, 0x6B1, bytes([vis])); e.wr(0x1F17, 0x6B6, bytes([sc]))
            e.wr(0x1F17, 0x6B4, bytes([R])); e.wr(0x1F17, 0x6B5, bytes([C]))
            saved = {r: e.r(r) for r in REGS}
            sp = e.r('sp') - 2
            e.wr(e.r('ss'), sp, struct.pack('<H', 0xFFF0)); e.w('sp', sp)
            for k, v in dict(ebx=key, edx=(row << 8) | col, ecx=vis, eax=0).items():
                e.w(k, v)
            e.w('ebx', (sc << 8) | key)
            e.uc.emu_start(e.lin(0x1000, 0x2746), stop, count=2000)
            dx = e.r('edx'); cx = e.r('ecx'); bx = e.r('ebx')
            res = (dx & 0xFF, (dx >> 8) & 0xFF, cx & 0xFF, (bx >> 8) & 0xFF)
            for r, v in saved.items():
                e.w(r, v)
            rows.append((n, key, col, row, vis, sc) + res)
with open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'tests', 'vectors_grid.h'), 'w') as f:
    f.write('/* generated by tools/gen_grid_vectors.py from the original 1000:125CF (items, key, cursor col row vis scroll, then the result col row vis scroll) */\nstatic const int grid_vectors[][10] = {\n')
    for r in rows:
        f.write('\t{%s},\n' % ', '.join(str(v) for v in r))
    f.write('};\n#define N_GRID_VECTORS %d\n' % len(rows))
print(len(rows), 'vectors')
