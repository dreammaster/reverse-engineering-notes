unsigned audioMusicTrackCount(GameKind game) {
    return game == GameYendor3 ? AudioMusicTracksYendor3 : AudioMusicTracksYendor2;
}

unsigned audioEffectCount(GameKind game) {
    return game == GameYendor3 ? AudioEffectsYendor3 : AudioEffectsYendor2;
}

static bool lookup(const Block *blocks, unsigned count, unsigned id, uint32_t *offset, uint32_t *length) {
    if (id == 0 || id > count) {
        return false;
    }
    *offset = blocks[id - 1].offset;
    *length = blocks[id - 1].length;
    return true;
}

bool audioMusicTrack(GameKind game, unsigned id, uint32_t *offset, uint32_t *length) {
    return game == GameYendor3 ? lookup(kMusicYendor3, AudioMusicTracksYendor3, id, offset, length)
                               : lookup(kMusicYendor2, AudioMusicTracksYendor2, id, offset, length);
}

bool audioEffect(GameKind game, unsigned id, uint32_t *offset, uint32_t *length) {
    return game == GameYendor3 ? lookup(kEffectsYendor3, AudioEffectsYendor3, id, offset, length)
                               : lookup(kEffectsYendor2, AudioEffectsYendor2, id, offset, length);
}
