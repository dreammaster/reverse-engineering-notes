const uint16_t (*uiRegionEntries(GameKind game, UiRegionTable table, unsigned *count))[5] {
    if ((unsigned)table >= UiRegionTableCount) {
        *count = 0;
        return 0;
    }
    if (game == GameYendor3) {
        *count = kYendor3Tables[table].count;
        return kYendor3Tables[table].rows;
    }
    *count = kYendor2Tables[table].count;
    return kYendor2Tables[table].rows;
}

unsigned uiRegionHit(GameKind game, UiRegionTable table, int x, int y) {
    unsigned count;
    const uint16_t (*rows)[5] = uiRegionEntries(game, table, &count);
    for (unsigned i = 0; i < count; i++) {
        if (x >= rows[i][0] && x <= rows[i][1] && y >= rows[i][2] && y <= rows[i][3]) {
            return rows[i][4];
        }
    }
    return 0;
}
