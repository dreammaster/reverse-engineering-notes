unsigned travelDestinationCount(GameKind game) {
    return game == GameYendor2 ? TravelDestinationCountYendor2 : TravelDestinationCountYendor3;
}

bool travelDestinationLookup(GameKind game, unsigned id, TravelDestination *out) {
    unsigned count = travelDestinationCount(game);
    if (id < 1 || id > count) {
        return false;
    }
    const TravelDestination *table = (game == GameYendor2) ? g_travelDestYendor2 : g_travelDestYendor3;
    *out = table[id - 1];
    return true;
}

static const TravelGateEntry *gateTable(GameKind game, unsigned *outCount) {
    if (game == GameYendor2) {
        *outCount = sizeof(g_travelGateYendor2) / sizeof(g_travelGateYendor2[0]);
        return g_travelGateYendor2;
    }
    *outCount = sizeof(g_travelGateYendor3) / sizeof(g_travelGateYendor3[0]);
    return g_travelGateYendor3;
}

static const TravelGateEntry *findGateEntry(GameKind game, unsigned destinationId) {
    unsigned count;
    const TravelGateEntry *table = gateTable(game, &count);
    for (unsigned i = 0; i < count; i++) {
        if (table[i].destinationId == destinationId) {
            return &table[i];
        }
    }
    return NULL;
}

TravelUnlockCheck travelCheckUnlock(GameKind game, unsigned destinationId, uint16_t destinationFlags,
                                     const uint8_t *globalFlags, size_t globalFlagsSize) {
    TravelUnlockCheck result = {TravelUnlockAlreadyUnlocked, 0, 0};
    const TravelGateEntry *entry = findGateEntry(game, destinationId);
    if (!entry) {
        return result; /* no gate entry at all -- nothing to unlock */
    }
    if (globalFlagTest(globalFlags, globalFlagsSize, entry->globalFlagIndex)) {
        return result; /* already unlocked */
    }
    if (entry->hasMsg != 0) {
        result.outcome = TravelUnlockDeniedWithMessage;
        result.messageId = entry->hasMsg;
        return result;
    }
    if (game == GameYendor3) {
        if (destinationFlags & 0x4000) {
            result.outcome = TravelUnlockDeniedFixedMessage;
            return result;
        }
        if (!(destinationFlags & 0x8000)) {
            result.outcome = TravelUnlockDeniedSilent;
            return result;
        }
        /* bit 0x8000 set -- fall through to the password prompt, same as Chapter 2's unconditional case */
    }
    result.outcome = TravelUnlockNeedsPassword;
    result.promptId = entry->promptId;
    return result;
}

TravelExamineOutcome travelExamineKey(GameKind game, unsigned destinationId, uint8_t *globalFlags, size_t globalFlagsSize,
                                      bool storyItemHeld) {
    if (game == GameYendor3 && globalFlagTest(globalFlags, globalFlagsSize, TravelStoryRealmFlag)) {
        if (storyItemHeld) {
            return TravelExamineStoryBlocked;
        }
        globalFlagClear(globalFlags, globalFlagsSize, TravelStoryRealmFlag);
    }
    const TravelGateEntry *entry = findGateEntry(game, destinationId);
    if (entry && !globalFlagTest(globalFlags, globalFlagsSize, entry->globalFlagIndex)) {
        return TravelExamineGateClosed;
    }
    return TravelExamineTravels;
}

bool travelResolvePassword(GameKind game, unsigned destinationId, const char *typedText,
                            uint8_t *globalFlags, size_t globalFlagsSize) {
    const TravelGateEntry *entry = findGateEntry(game, destinationId);
    if (!entry || !entry->password) {
        return false;
    }
    size_t len = strlen(entry->password);
    size_t typedLen = typedText ? strlen(typedText) : 0;
    if (typedLen < len || strncmp(entry->password, typedText, len) != 0) {
        return false;
    }
    globalFlagSet(globalFlags, globalFlagsSize, entry->globalFlagIndex);
    return true;
}
