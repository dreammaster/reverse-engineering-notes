enum {
    ExpirySoundYendor2 = 0x28, /* _val20 */
    ExpirySoundYendor3 = 0x08
};

unsigned effectCount(GameKind game) {
    return game == GameYendor2 ? EffectCountYendor2 : EffectCountYendor3;
}

static void copyRow(const uint16_t *row, EffectDef *out) {
    out->sound = row[0];
    out->icon = row[1];
    out->magnitudeMin = row[2];
    out->magnitudeMax = row[3];
    out->costFlags = row[4];
    out->modeFlags = row[5];
}

bool effectGetDef(GameKind game, unsigned id, EffectDef *out) {
    if (id >= effectCount(game)) {
        return false;
    }
    copyRow(game == GameYendor2 ? g_effectsYendor2[id] : g_effectsYendor3[id], out);
    if (id == 0 || id == 22) {
        out->sound = game == GameYendor2 ? ExpirySoundYendor2 : ExpirySoundYendor3;
    }
    return true;
}

void effectParseDef(const uint8_t raw[EffectDefSize], EffectDef *out) {
    uint16_t row[6];
    for (int i = 0; i < 6; i++) {
        row[i] = (uint16_t)(raw[i * 2] | (raw[i * 2 + 1] << 8));
    }
    copyRow(row, out);
}

EffectSpend effectSpend(const EffectDef *def) {
    if (def->costFlags & EffectCostHp) {
        return EffectSpendHp;
    }
    if (def->costFlags & EffectCostMp) {
        return EffectSpendMp;
    }
    if (def->costFlags & EffectCostHpAndMp) {
        return EffectSpendHpAndMp;
    }
    if (def->costFlags & EffectCostGold) {
        return EffectSpendGold;
    }
    if (def->costFlags & EffectCostOre1) {
        return EffectSpendOre1;
    }
    if (def->costFlags & EffectCostOre2) {
        return EffectSpendOre2;
    }
    return EffectSpendNone;
}

uint16_t effectInflictedStatus(const EffectDef *def) {
    return def->costFlags & EffectInflictMask;
}

bool effectRollsMagnitude(const EffectDef *def) {
    return (def->costFlags & (EffectCostGold | EffectCostOre2 | EffectCostOre1)) == 0;
}

uint16_t effectRandomBound(const EffectDef *def) {
    return (uint16_t)(def->magnitudeMax - def->magnitudeMin);
}

uint16_t effectMagnitude(const EffectDef *def, uint16_t level, uint16_t randomValue) {
    if (def->modeFlags & EffectModeMagnitudeFixed) {
        return def->magnitudeMin;
    }
    uint16_t base = def->magnitudeMin;
    if (!(def->modeFlags & EffectModeMagnitudeScaled)) {
        base = (uint16_t)(randomValue + def->magnitudeMin);
    }
    return (uint16_t)(base * level);
}

uint16_t effectResistanceBonus(const EffectDef *def, const uint8_t *partyRecord) {
    static const struct {
        uint16_t status;
        PartyProtection protection;
    } pairs[] = {
        {PartyStatusSick, PartyProtectionSickness},
        {PartyStatusPoisoned, PartyProtectionPoison},
        {PartyStatusDiseased, PartyProtectionDisease},
        {PartyStatusParalyzed, PartyProtectionParalyze},
        {PartyStatusFrozen, PartyProtectionFrozen},
        {PartyStatusStoned, PartyProtectionStoning},
        {PartyStatusJinxed, PartyProtectionJinxing},
        {PartyStatusHexed, PartyProtectionHexing},
        {PartyStatusCursed, PartyProtectionCursing},
    };
    if (!(def->modeFlags & EffectModeRollResistance)) {
        return 0;
    }
    uint16_t total = 0;
    for (size_t i = 0; i < sizeof(pairs) / sizeof(pairs[0]); i++) {
        if (def->costFlags & pairs[i].status) {
            total = (uint16_t)(total + partyGetProtection(partyRecord, pairs[i].protection));
        }
    }
    return total;
}
