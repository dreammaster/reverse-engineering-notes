#!/usr/bin/env python3
"""Writes src/ultima6/se_front_data.inc: the texts and tables of Savage Empire's front end (SAVAGE.EXE, DS file base 0xE6A0), read off the executable's data segment:

    gen_se_front.py se/game/SAVAGE/SAVAGE.EXE src/ultima6/se_front_data.inc

The strings are the ones the routines of se/se_savage.asm print: the ending sub_15E82 (the pointer table at ds:0637, the strings of the date), the pages of the Introduction sub_15D3B (ds:0623),
the creation sub_150AC / sub_154BD / sub_155A0 (the hut, the question table at ds:0564, 12 bytes a row), the menu sub_14978 (the tables at ds:05DC and ds:05E4).
"""
import struct
import sys

exe = open(sys.argv[1], 'rb').read()
DS = 0xE6A0


def s(o):
    e = exe.index(b'\0', DS + o)
    return exe[DS + o:e].decode('latin1')


def w(o):
    return struct.unpack_from('<H', exe, DS + o)[0]


def c(t):  # a C string literal (the newlines as \012: a character that a shell edit cannot lose)
    out = ''
    for ch in t:
        if ch == '\n':
            out += '\\n'
        elif ch == '"':
            out += '\\"'
        elif ch == '\\':
            out += '\\\\'
        else:
            out += ch
    return '"%s"' % out


with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/gen_se_front.py from SAVAGE.EXE\'s data segment. Do not edit.\n')
    f.write('// The pages of the Introduction (sub_15D3B; ds:0623), one under each picture of CREATE.LZC item 5\n')
    f.write('static const char *const SE_PAGES[10] = {\n')
    for k in range(10):
        f.write('\t%s,\n' % c(s(w(0x623 + 2 * k))))
    f.write('};\n')
    f.write('// The ending (sub_15E82; ds:0637): 14 pages and the two lines that end it\n')
    f.write('static const char *const SE_END_TEXT[16] = {\n')
    for k in range(16):
        f.write('\t%s,\n' % c(s(w(0x637 + 2 * k))))
    f.write('};\n')
    f.write('// The creation: sub_154BD\'s texts (ds:0D7C, 0DD3, 0E4F, 0EBC, 0EFE, 0F68, 0FC8), the refusals (ds:0CBD, 0D0F)\n')
    f.write('static const char *const SE_CREATE_TEXT[9] = {\n')
    for o in (0xD7C, 0xDD3, 0xE4F, 0xEBC, 0xEFE, 0xF68, 0xFC8, 0xCBD, 0xD0F):
        f.write('\t%s,\n' % c(s(o)))
    f.write('};\n')
    f.write('// The questions (ds:0564, 6 rows of 12 bytes): the texts (0 when there is none) of the first, second, third and fourth line, and the stat that answer A and answer B raise (0 intelligence, 1 dexterity, 2 strength)\n')
    f.write('struct SeQuestion {\n\tconst char *line[4];\n\tint a, b;\n};\n')
    f.write('static const SeQuestion SE_QUESTIONS[6] = {\n')
    for k in range(6):
        r = [w(0x564 + 12 * k + 2 * j) for j in range(6)]
        t = ['0' if r[j] == 0 else c(s(r[j])) for j in range(4)]
        f.write('\t{{%s}, %d, %d},\n' % (', '.join(t), r[4], r[5]))
    f.write('};\n')
    f.write('// The menu (sub_14978; ds:05DC the y of each choice, ds:05E4 the frame of CREATE.LZC item 0 that shows it)\n')
    f.write('static const int SE_MENU_Y[4] = {%s};\n' % ', '.join(str(w(0x5DC + 2 * i)) for i in range(4)))
    f.write('static const int SE_MENU_FRAME[4] = {%s};\n' % ', '.join(str(w(0x5E4 + 2 * i)) for i in range(4)))
print('ok')
