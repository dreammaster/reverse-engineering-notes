INCLUDE = re.compile(r'#include "(engine|files|ultima6|martian_dreams|savage_empire)/')


def with_std(rel, text):
    if rel == 'engine/std_headers.h':
        return text
    first_inc = text.find('#include')
    guard = text.find('#ifndef')
    marker = '#include "ultima/ultima6/engine/std_headers.h"' + chr(10)
    if rel.endswith('.h') and guard >= 0 and (first_inc < 0 or guard < first_inc):
        # after the include guard
        end = text.index(chr(10), text.index('#define', guard)) + 1
        return text[:end] + chr(10) + marker + text[end:]
    return marker + chr(10) + text


def transform(text):
    text = text.replace('\r\n', '\n')
    text = INCLUDE.sub(r'#include "ultima/ultima6/\1/', text)
    # qualified references from the global namespace
    text = text.replace('::Ultima6::', '::Ultima::Ultima6::')
    # the outer namespace: the first `namespace Ultima6 {` opens it, the last `} // namespace Ultima6` closes it
    first = text.find('namespace Ultima6 {')
    if first >= 0:
        text = text[:first] + 'namespace Ultima {\n' + text[first:]
        last = text.rfind('} // namespace Ultima6')
        end = last + len('} // namespace Ultima6')
        text = text[:end] + '\n} // namespace Ultima' + text[end:]
    return text


def patch(rel, text):
    if rel == 'engine/framebuffer.cpp':
        # no PNG writer in the host: the function stays, doing nothing
        # (the helpers in the anonymous namespace above it use FILE, which the host forbids)
        a = text.index('namespace {')
        b = text.index(chr(10) + '}' + chr(10), text.index('bool Framebuffer::savePng')) + 3
        stub = 'bool Framebuffer::savePng(const std::string &, int) const {' + chr(10) + chr(9) + 'return false;' + chr(10) + '}' + chr(10)
        text = text[:a] + stub + text[b:]
        text = text.replace('#include <cstdio>' + chr(10), '')
    return text


def patch_metaengine(dest_root):
    """Routes the three games to the new engine in engines/ultima/metaengine.cpp (between markers, so a run replaces the last)."""
    path = os.path.join(dest_root, 'engines', 'ultima', 'metaengine.cpp')
    text = open(path, encoding='utf-8', newline='').read()
    crlf = '\r\n' in text
    text = text.replace('\r\n', '\n')
    text = re.sub(r'// BEGIN generated by tools/sync_scummvm.py \(\w+\)\n.*?// END generated\n', '', text, flags=re.S)
    includes = ('// BEGIN generated by tools/sync_scummvm.py (include)\n'
                '#ifdef ENABLE_ULTIMA6NEW\n'
                '#ifdef ENABLE_ULTIMA6\n'
                '#error "ultima6 (Nuvie) and ultima6new use the same namespace: enable only one of them"\n'
                '#endif\n'
                '#include "ultima/ultima6/ultima6_engine.h"\n'
                '#endif\n'
                '// END generated\n')
    anchor = '#ifdef ENABLE_ULTIMA8\n#include "ultima/ultima8/ultima8.h"'
    text = text.replace(anchor, includes + anchor, 1)
    create = ('\t// BEGIN generated by tools/sync_scummvm.py (create)\n'
              '#ifdef ENABLE_ULTIMA6NEW\n'
              '\tcase Ultima::GAME_ULTIMA6:\n'
              '\tcase Ultima::GAME_MARTIAN_DREAMS:\n'
              '\tcase Ultima::GAME_SAVAGE_EMPIRE:\n'
              '\t\t*engine = new Ultima::Ultima6::Ultima6Engine(syst, gd);\n'
              '\t\tbreak;\n'
              '#endif\n'
              '\t// END generated\n')
    anchor = '\tswitch (gd->gameId) {\n'
    text = text.replace(anchor, anchor + create, 1)
    if crlf:
        text = text.replace('\n', '\r\n')
    with open(path, 'w', newline='') as f:
        f.write(text)


def patch_configure(dest_root):
    """configure.engine: ultima6new is a sub-engine of ultima, off unless asked for (it can't be built together with ultima6, Nuvie)."""
    path = os.path.join(dest_root, 'engines', 'ultima', 'configure.engine')
    text = open(path, encoding='utf-8', newline='').read()
    crlf = '\r\n' in text
    text = text.replace('\r\n', '\n')
    if 'ultima6new' not in text:
        text = text.replace('ultima4 ultima6 ultima8"', 'ultima4 ultima6 ultima6new ultima8"', 1)
        line = 'add_engine ultima6 "Ultima VI - The False Prophet" yes "" "" "highres 16bit lua"\n'
        text = text.replace(line, line + 'add_engine ultima6new "Ultima VI, Martian Dreams, Savage Empire (new engine, instead of ultima6)" no "" "" "16bit"\n', 1)
    if crlf:
        text = text.replace('\n', '\r\n')
    if text != open(path, encoding='utf-8', newline='').read():  # (a changed configure.engine makes make run configure again)
        with open(path, 'w', newline='') as f:
            f.write(text)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        f.write(text)


def main(dest_root):
    dest = os.path.join(dest_root, 'engines', 'ultima', 'ultima6')
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    objs = []
    for d in DIRS:
        for name in sorted(os.listdir(os.path.join(SRC, d))):
            rel = d + '/' + name
            if rel in SKIP:
                continue
            overlay = os.path.join(OVERLAY, d, name)
            path = overlay if os.path.exists(overlay) else os.path.join(SRC, d, name)
            text = open(path, encoding='utf-8').read()
            if name.endswith(('.cpp', '.h')):
                text = HEADER + with_std(rel, patch(rel, transform(text)))
            write(os.path.join(dest, d, name), text)
            if name.endswith('.cpp'):
                objs.append('ultima6/%s/%s.o' % (d, name[:-4]))
    # files that exist only as overlays
    for d in os.listdir(OVERLAY) if os.path.isdir(OVERLAY) else []:
        for name in os.listdir(os.path.join(OVERLAY, d)):
            if not os.path.exists(os.path.join(SRC, d, name)):
                text = open(os.path.join(OVERLAY, d, name), encoding='utf-8').read()
                if name.endswith(('.cpp', '.h')):
                    text = HEADER + text
                write(os.path.join(dest, d, name), text)
                if name.endswith('.cpp'):
                    objs.append('ultima6/%s/%s.o' % (d, name[:-4]))
    for name in sorted(os.listdir(GLUE)) if os.path.isdir(GLUE) else []:
        text = open(os.path.join(GLUE, name), encoding='utf-8').read()
        if name.endswith(('.cpp', '.h')):
            text = HEADER + text
        write(os.path.join(dest, name), text)
        if name.endswith('.cpp'):
            objs.append('ultima6/%s.o' % name[:-4])
    # module.mk: the block between the markers
    mk = os.path.join(dest_root, 'engines', 'ultima', 'module.mk')
    block = '# BEGIN generated by tools/sync_scummvm.py\nifdef ENABLE_ULTIMA6NEW\nMODULE_OBJS += \\\n' + ' \\\n'.join('\t' + o for o in sorted(objs)) + '\nendif\n# END generated\n'
    text = open(mk, encoding='utf-8', newline='').read()
    crlf = '\r\n' in text
    text = text.replace('\r\n', '\n')
    # (rules.mk is included after the objects are listed, so the block goes before the plugin section)
    text = re.sub(r'\n?# BEGIN generated by tools/sync_scummvm.py\n.*?# END generated\n', '', text, flags=re.S)
    anchor = '# This module can be built as a plugin'
    text = text.replace(anchor, block + '\n' + anchor, 1)
    if crlf:
        text = text.replace('\n', '\r\n')
    write(mk, text)
    patch_metaengine(dest_root)
    patch_configure(dest_root)
    print('%d objects' % len(objs))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'C:/dev/scummvm')
