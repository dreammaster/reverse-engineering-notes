#!/usr/bin/env python3
"""Writes src/ultima6/md_create_data.inc: what Martian Dreams' character creation (MARTIAN.EXE sub_18557, the questions of Dr. Freud) is made of.

    gen_md_create.py md/md_martian.asm md/game/MARTIAN/MARTIAN.EXE src/ultima6/md_create_data.inc

- the table of the scenes (sub_17E7A reads it at ds:01E3, four words each: the line of SCENETXT item 5 and its colour (the sign), the face, whether the face talks, how the scene waits: seconds, -1 any key,
  -2 a or b, -3 a to c, -4 the name),
- the questions as a program: sub_18557's code between the first question and loc_19166 only compares the answers, keeps them in registers and sets the three stats to one of the random numbers, so
  it is turned into small operations (0 ask scene a; 1 store the answer in register a; 2 compare register a with b; 3 jump if equal; 4 jump if not equal; 5 jump; 6 stat a = random number b; 7 end).
"""
import re
import struct
import sys

asm, exe_path, out_path = sys.argv[1:4]
exe = open(exe_path, 'rb').read()
DS = 0x186A0
lines = open(asm, encoding='utf-8', errors='replace').read().split('\n')
start = next(i for i, l in enumerate(lines) if re.match(r'sub_18557\s+proc', l))
end = next(i for i in range(start, len(lines)) if re.match(r'sub_18557\s+endp', lines[i]))
code = [l.split(';')[0].rstrip() for l in lines[start:end]]
code = [l for l in code if l.strip()]

# the calls sub_17E7A(...) with the scene number pushed first
res = []
i = 0
while i < len(code):
    m = re.match(r'\s+mov\s+ax, ([0-9A-F]+)h?$', code[i])
    z = re.match(r'\s+xor\s+ax, ax$', code[i])
    if (m or z) and i + 2 < len(code) and 'push    ax' in code[i + 1] and 'lea     ax, [bp+var_1B2]' in code[i + 2]:
        j = i
        while 'call    near ptr sub_17E7A' not in code[j]:
            j += 1
        res.append('Q %d' % (0 if z else (int(m.group(1), 16) if code[i].strip().endswith('h') else int(m.group(1)))))
        i = j + 2  # (add sp, 10h)
        continue
    res.append(code[i].strip())
    i += 1
s = next(i for i, l in enumerate(res) if l == 'Q 0')
e = next(i for i, l in enumerate(res) if l.startswith('loc_19166'))
region = res[s:e]

REGS = {'ax': 0, 'di': 1, 'si': 2, '[bp+var_12]': 3, '[bp+var_14]': 4, '[bp+var_16]': 5}
STORE = {'di': 1, 'si': 2, '[bp+var_12]': 3, '[bp+var_14]': 4, '[bp+var_16]': 5}
ATTR = {'byte_2A097': 0, 'byte_2A197': 1, 'byte_2A297': 2}
RAND = {'byte ptr [bp+var_1C]': 0, 'byte ptr [bp+var_1E]': 1}
ops = []
labels = {}
fix = []
i = 0
while i < len(region):
    l = region[i]
    m = re.match(r'(loc_[0-9A-F]+):', l)
    if m:
        labels[m.group(1)] = len(ops)
        i += 1
        continue
    if l.startswith('Q '):
        ops.append((0, int(l[2:]), 0))
    elif re.match(r'mov\s+(di|si|\[bp\+var_1[246]\]), ax$', l):
        ops.append((1, STORE[re.match(r'mov\s+(\S+), ax', l).group(1)], 0))
    elif l.startswith('cmp'):
        m = re.match(r'cmp\s+(\S+), ([0-9A-F]+)h$', l)
        ops.append((2, REGS[m.group(1)], int(m.group(2), 16)))
    elif l.startswith(('jz', 'jnz', 'jmp')):
        m = re.match(r'(jz|jnz|jmp)\s+(?:short )?(loc_[0-9A-F]+)', l)
        fix.append(len(ops))
        ops.append(({'jz': 3, 'jnz': 4, 'jmp': 5}[m.group(1)], m.group(2), 0))
    elif l.startswith('mov     al, byte ptr'):
        m = re.match(r'mov\s+al, (byte ptr \[bp\+var_1[CE]\])$', l)
        n = re.match(r'mov\s+(byte_2A[012]97), al$', region[i + 1])
        ops.append((6, ATTR[n.group(1)], RAND[m.group(1)]))
        i += 1
    else:
        raise SystemExit('unknown: ' + l)
    i += 1
labels['loc_19166'] = len(ops)
ops.append((7, 0, 0))
for k in fix:
    ops[k] = (ops[k][0], labels[ops[k][1]], 0)

table = []
for k in range(93):
    table.append(struct.unpack_from('<4h', exe, DS + 0x1E3 + 8 * k))
assert table[92][0] == 0 and all(t[0] != 0 or t[1] == 2 for t in table[7:8])

with open(out_path, 'w') as f:
    f.write('// Generated by tools/gen_md_create.py from MARTIAN.EXE (sub_18557, sub_17E7A and their table at ds:01E3). Do not edit.\n')
    f.write('// MD_CREATE_SCENES: the line of SCENETXT item 5 (negative: the other colour), the face, whether it talks, how the scene waits (seconds; -1 any key; -2 a or b; -3 a to c; -4 the name);\n')
    f.write('// a scene ends at the next entry whose line is 0\n')
    f.write('static const int16_t MD_CREATE_SCENES[%d][4] = {\n' % len(table))
    for t in table:
        f.write('\t{%d, %d, %d, %d},\n' % t)
    f.write('};\n')
    f.write('// MD_CREATE_OPS: 0 ask scene a (the key comes back in the accumulator), 1 store the accumulator in register a (1 di, 2 si, 3 to 5 the answers), 2 compare register a (0 accumulator) with b,\n')
    f.write('// 3 jump to a if equal, 4 if not equal, 5 jump, 6 stat a (0 strength, 1 dexterity, 2 intelligence) = random number b, 7 end\n')
    f.write('struct MdCreateOp {\n\tuint8_t op;\n\tint16_t a, b;\n};\n')
    f.write('static const MdCreateOp MD_CREATE_OPS[%d] = {\n' % len(ops))
    for k in range(0, len(ops), 6):
        f.write('\t' + ' '.join('{%d, %d, %d},' % o for o in ops[k:k + 6]) + '\n')
    f.write('};\n')
print(len(ops), 'ops', len(table), 'scenes')
