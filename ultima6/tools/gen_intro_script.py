#!/usr/bin/env python3
"""Writes src/ultima6/md_intro_script.inc from the calls recorded by tools/emulate_intro.py (md/intro_ops.json):

    gen_intro_script.py md/intro_ops.json md/game/MARTIAN/MARTIAN.EXE src/ultima6/md_intro_script.inc
"""
import json
import sys

ops = json.load(open(sys.argv[1]))['ops']
exe = open(sys.argv[2], 'rb').read()
DS = 0x186A0


def name(off):
    return exe[DS + off:DS + off + 16].split(b'\0')[0].decode().upper()


files = []
OPS = {'load': 0, 'text': 1, 'clear': 2, 'draw': 3, 'caption': 4, 'present': 5, 'wait': 6, 'fadein': 7, 'fadeout': 8, 'dword_2817A': 9, 'dword_28172': 10}
out = []
for o in ops:
    c = o['call']
    if c in ('free', 'music', 'sub_20951', 'sub_20D32'):
        continue
    if c == 'load':
        n = name(o['file'])
        if n not in files:
            files.append(n)
        out.append((0, o['tag'] - 0x4001, files.index(n), o['item'], 0))
    elif c == 'text':
        out.append((1, o['item'], 0, 0, 0))
    elif c == 'clear' or c == 'present' or c == 'fadein' or c == 'fadeout':
        out.append((OPS[c], 0, 0, 0, 0))
    elif c == 'draw':
        out.append((3, o['frame'], o['handle'] - 0x4001, o['x'], o['y']))
    elif c == 'caption':
        t = o['text'] - 0x2000
        out.append((4, t >> 8, t & 0xFF, o['y'], 0))
    elif c == 'wait':
        out.append((6, o['ms'], 0, 0, 0))
    elif c == 'dword_2817A':
        a = o['args']  # frame, scale, y, 0, seg, handle, x, 0, dest
        out.append((9, a[0], a[5] - 0x4001, a[6], a[2]))
    elif c == 'dword_28172':
        a = o['args']
        out.append((10, a[2], a[3], 0, 0))
    else:
        raise SystemExit('unknown ' + c)

with open(sys.argv[3], 'w') as f:
    f.write('// Generated by tools/gen_intro_script.py from the introduction routine of MARTIAN.EXE (sub_19266), run on tools/emulate_intro.py. Do not edit.\n')
    f.write('static const char *const MD_INTRO_FILES[%d] = {%s};\n' % (len(files), ', '.join('"%s"' % n for n in files)))
    f.write('// op, a, b, c, d: 0 load (handle a, file b, item c), 1 text set a, 2 clear, 3 draw (frame a, handle b, x c, y d), 4 caption (set a, line b, y c), 5 present, 6 wait a ms, 7 fade in, 8 fade out,\n')
    f.write('// 9 the pan of the hand (frame a, handle b, x c, y d), 10 a dot (x a, y b)\n')
    f.write('struct MdIntroOp {\n\tuint8_t op;\n\tint16_t a, b, c, d;\n};\n')
    f.write('static const MdIntroOp MD_INTRO_OPS[%d] = {\n' % len(out))
    for i in range(0, len(out), 6):
        f.write('\t' + ' '.join('{%d, %d, %d, %d, %d},' % o for o in out[i:i + 6]) + '\n')
    f.write('};\n')
print(len(out), 'ops,', files)
