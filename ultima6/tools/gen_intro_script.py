#!/usr/bin/env python3
"""Writes src/ultima6/md_intro_script.inc from the calls recorded by tools/emulate_intro.py for the routines of MARTIAN.EXE that play the introduction (sub_19266), the ending (sub_15C84, with the
avatar's type word_29B98 = 0x157) and the credits (sub_1675E, with word_29662 = 1):

    emulate_intro.py md/md_martian.asm md/game/MARTIAN/MARTIAN.EXE md/intro_ops.json
    emulate_intro.py md/md_martian.asm md/game/MARTIAN/MARTIAN.EXE md/ops_sub_15C84.json sub_15C84 word_29B98=0x157
    emulate_intro.py md/md_martian.asm md/game/MARTIAN/MARTIAN.EXE md/ops_sub_1675E.json sub_1675E word_29662=1
    gen_intro_script.py md/game/MARTIAN/MARTIAN.EXE src/ultima6/md_intro_script.inc md/intro_ops.json md/ops_sub_15C84.json md/ops_sub_1675E.json
"""
import json
import sys

exe = open(sys.argv[1], 'rb').read()
DS = 0x186A0


def name(off):
    return exe[DS + off:DS + off + 16].split(b'\0')[0].decode().upper()


files = []
out = []
starts = []
for path in sys.argv[3:]:
    starts.append(len(out))
    for o in json.load(open(path))['ops']:
        c = o['call']
        if c == 'other' and o['fn'] == 'sub_1F2AE':  # the wait for the vertical retrace (70 a second)
            out.append((6, 14, 0, 0, 0, 0))
            continue
        if c in ('free', 'music', 'sub_20951', 'sub_20D32', 'other'):
            continue
        if c == 'load':
            n = name(o['file'])
            if n not in files:
                files.append(n)
            out.append((0, o['tag'] - 0x4001, files.index(n), o['item'], 0, 0))
        elif c == 'text':
            out.append((1, o['item'], 0, 0, 0, 0))
        elif c in ('clear', 'present', 'fadein', 'fadeout'):
            out.append(({'clear': 2, 'present': 5, 'fadein': 7, 'fadeout': 8}[c], 0, 0, 0, 0, 0))
        elif c == 'draw':
            out.append((3, o['frame'], o['handle'] - 0x4001, o['x'], o['y'], 0))
        elif c == 'caption':
            t = o['text'] - 0x2000
            out.append((4, t >> 8, t & 0xFF, o['y'], 0, 0))
        elif c == 'wait':
            out.append((6, o['ms'], 0, 0, 0, 0))
        elif c == 'dword_2817A':
            a = o['args']  # the arguments in the order pushed: ?, scale, scroll, frame, seg, handle, y, x, dest
            if path == sys.argv[3]:  # the introduction: the first guess (APPROX 90)
                out.append((9, a[0], a[5] - 0x4001, a[6], a[2], 0))
            else:
                out.append((11, a[3], a[5] - 0x4001, a[7], a[6], a[1]))
        elif c == 'dword_28172':
            a = o['args']
            out.append((10, a[2], a[3], 0, 0, 0))
        else:
            raise SystemExit('unknown ' + c)
starts.append(len(out))

with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/gen_intro_script.py from the introduction (sub_19266), the ending (sub_15C84) and the credits (sub_1675E) of MARTIAN.EXE, run on tools/emulate_intro.py. Do not edit.\n')
    f.write('static const char *const MD_INTRO_FILES[%d] = {%s};\n' % (len(files), ', '.join('"%s"' % n for n in files)))
    f.write('// op, a, b, c, d, e: 0 load (handle a, file b, item c), 1 text set a, 2 clear, 3 draw (frame a, handle b, x c, y d), 4 caption (set a, line b, y c), 5 present, 6 wait a ms, 7 fade in, 8 fade out,\n')
    f.write('// 9 the pan of the introduction (frame a, handle b, x c, y d), 10 a dot (x a, y b), 11 a draw of the driver entry 0x2817A (frame a, handle b, x c, y d, size e in 256ths)\n')
    f.write('struct MdIntroOp {\n\tuint8_t op;\n\tint16_t a, b, c, d, e;\n};\n')
    f.write('// the scripts: the introduction, the ending, the credits (the first call of each, and the end of the last)\n')
    f.write('static const size_t MD_SCRIPT_START[%d] = {%s};\n' % (len(starts), ', '.join(str(s) for s in starts)))
    f.write('static const MdIntroOp MD_INTRO_OPS[%d] = {\n' % len(out))
    for i in range(0, len(out), 5):
        f.write('\t' + ' '.join('{%d, %d, %d, %d, %d, %d},' % o for o in out[i:i + 5]) + '\n')
    f.write('};\n')
print(len(out), 'ops', starts, files)
