#!/usr/bin/env python3
"""Writes src/ultima6/md_sfx_data.inc: the sound effects of Martian Dreams, one 8-byte step each (flags, timbre + 1, note, velocity, duration in timer ticks (a word), second note, 0):

    gen_md_sfx.py md/game/MARTIAN src/ultima6/md_sfx_data.inc

GAME.EXE keeps 56 of them at ds:16DC (sub_303A9 plays effect n through sub_375FB with the step at ds:16DC + 8 n), MARTIAN.EXE two at ds:04CB (sub_20951 in the credits and the introduction).
"""
import sys

d = sys.argv[1]
game = open(d + '/GAME.EXE', 'rb').read()
mart = open(d + '/MARTIAN.EXE', 'rb').read()
gbase = game.find(b'strax.drv\x00MThd') - 0x2E2B  # the data segment of GAME.EXE starts so that "strax.drv" is at ds:2E2B
mbase = 0x186A0                                    # MARTIAN.EXE's
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/gen_md_sfx.py from GAME.EXE (ds:16DC) and MARTIAN.EXE (ds:04CB). Do not edit.\n')
    f.write('static const uint8_t MD_GAME_EFFECTS[56][8] = {\n')
    for i in range(56):
        f.write('\t{%s},\n' % ', '.join(str(b) for b in game[gbase + 0x16DC + 8 * i:gbase + 0x16DC + 8 * i + 8]))
    f.write('};\nstatic const uint8_t MD_FRONT_EFFECTS[2][8] = {\n')
    for i in range(2):
        f.write('\t{%s},\n' % ', '.join(str(b) for b in mart[mbase + 0x4CB + 8 * i:mbase + 0x4CB + 8 * i + 8]))
    f.write('};\n')
