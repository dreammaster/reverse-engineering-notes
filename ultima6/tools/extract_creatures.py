#!/usr/bin/env python3
"""
Reads the creature / movement class table out of a game's GAME.EXE (the code segment table that starts with the object
types: a word per class ending in a zero word, then seven byte columns - strength, dexterity, intelligence, experience,
damage, hit points and alignment (top bits) - then a word of movement class flags per class) and writes it as C++.

    extract_creatures.py <exe> <game> > table.inc

The layouts were found by comparing Ultima VI (the table at the start of its segment 066, columns 64 bytes apart) with the
two spin-offs (columns 50 and 48 bytes apart), see docs/spinoffs.md.
"""

import struct
import sys

LAYOUTS = {
    # first type, entries, spacing of the columns, offset of the first column and of the flags (from the first type)
    "u6": (197792, 63, 64, 0x82, 0x242),
    "md": (201298, 48, 50, 102, 452),
    "se": (206898, 48, 48, 98, 434),
}


# the side bits of the status byte (0x40 the party's, 0x20 the monsters') as the alignments 0 good, 1 neutral, 2 evil, 3 chaotic
ALIGN = {0x40: 0, 0x00: 1, 0x20: 2, 0x60: 3}


def reverse15(word):
    out = 0
    for n in range(15):
        if word & (1 << n):
            out |= 1 << (14 - n)
    return out


# the weapon damage, weapon range and armour class lists: (offset of the types, offset of the values, entries) from the start of the data segment, which starts
# at this file offset in each executable; found from the three small look-up functions (docs/spinoffs.md)
WEAPONS = {
    "md": (208560, {"DAMAGE": (0xBB2, 0xBF2, 32), "RANGE": (0xC12, 0xC36, 18), "ARMOUR": (0xCFA, 0xD3E, 34)}),
    "se": (208480, {"DAMAGE": (0x105E, 0x1094, 27), "RANGE": (0xF56, 0xF72, 14), "ARMOUR": (0xF3E, 0xF4E, 8)}),
}


def main():
    path, game = sys.argv[1], sys.argv[2]
    base, count, step, strs, flags = LAYOUTS[game]
    d = open(path, "rb").read()
    print("// generated by tools/extract_creatures.py from the %s executable: class types, class flags and the creature numbers" % game)
    types = [struct.unpack_from("<H", d, base + 2 * i)[0] for i in range(count)]
    cols = [[d[base + strs + c * step + i] for i in range(count)] for c in range(7)]
    cflags = [struct.unpack_from("<H", d, base + flags + 2 * i)[0] for i in range(count)]
    print("static const uint16_t %s_CLASS_TYPES[%d] = {%s};" % (game.upper(), count, ", ".join("0x%X" % t for t in types)))
    print("static const uint16_t %s_CLASS_FLAGS[%d] = {%s};" % (game.upper(), count, ", ".join("0x%X" % f for f in cflags)))
    print("static const CreatureStats %s_CREATURES[] = {" % game.upper())
    for i in range(count):
        s, dx, it, ex, dm, hp, al = (cols[c][i] for c in range(7))
        print("\t{%d, %d, %d, %d, %d, %d, %d, 0x%X, %d}, // class %d" % (types[i], s, dx, it, hp, dm, ALIGN[al & 0x60], reverse15(cflags[i]), ex, i))
    print("};")
    if game in WEAPONS:
        ds, lists = WEAPONS[game]
        for name, (tOff, vOff, n) in lists.items():
            pairs = ["{%d, %d}" % (struct.unpack_from("<H", d, ds + tOff + 2 * i)[0], d[ds + vOff + i]) for i in range(n)]
            print("static const TypeValue %s_%s[] = {%s};" % (game.upper(), name, ", ".join(pairs)))


main()
