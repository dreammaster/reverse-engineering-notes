#!/usr/bin/env python3
"""Coverage report: which routines of the original did the recompiled game replace by hand, and how well is each checked?

    python3 tools/mm3_coverage.py [lockstep stats.json ...] > docs/lockstep-coverage.md

For every host routine the translated game calls (RHOST in src/gen/game_gen.c) the table says
  * what it is   -- readable rewrite (src/gen/readable.txt), rules, C library helper, or hand-written DOS/video/sound/input
  * how it is checked
      lockstep-R   the original code is run in the emulator and its results/memory effects compared (tools/mm3_lockstep.py)
      difftest     tests/difftest.sh compares it with the translated original on random states (src/game_diff.c)
      replay       the recorded effect is replayed into the original run: only the *callers* are checked, not the routine itself
  * how often the given lockstep runs exercised it.
It also lists the translated routines that no lockstep run entered.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")
sys.path.insert(0, HERE)
import mm3_lockstep as L  # noqa: E402


def canon(n):
    return L.canon(n)


def main():
    stats = {}
    fcount = {}
    runs = 0
    for path in sys.argv[1:]:
        d = json.load(open(path))
        runs += 1
        for n, k in d.get("functions", {}).items():
            fcount[n] = fcount.get(n, 0) + k
        for n, st in d["calls"].items():
            e = stats.setdefault(n, {"class": st["class"], "count": 0})
            e["count"] += st["count"]
    gen = open(os.path.join(SRC, "gen", "game_gen.c")).read()
    hosts = sorted(set(canon(n) for n in re.findall(r"RHOST\(c, (\w+),", gen)))
    fns = sorted(set(re.findall(r"^static void fn_(\w+)\(Cpu \*c\);", gen, re.M)))
    readable = set(l.strip() for l in open(os.path.join(SRC, "gen", "readable.txt")) if l.strip())
    diff = set(re.findall(r'\{ "(\w+)", host_\w+, \d+, \d+,', open(os.path.join(SRC, "game_diff.c")).read()))
    ns = argparse_ns()
    cls = L.Lockstep.load_classes(ns, ns)
    out = ["# Lockstep coverage", "",
           "Generated by `tools/mm3_coverage.py` from %d lockstep run(s).  *R* = the original code was run and compared; *E* = the recorded effect was replayed." % runs, "",
           "| host routine | kind | checked by | lockstep calls |", "|---|---|---|---|"]
    for h in hosts:
        if h in readable:
            kind = "readable rewrite"
        elif h in L.RULES_HOSTS:
            kind = "rules (rules.c)"
        elif h in L.LIBC_HOSTS:
            kind = "C library helper"
        elif h.startswith("vdrv_"):
            kind = "video module"
        elif h.startswith("sub_269") or h.startswith("sound"):
            kind = "sound"
        else:
            kind = "hand-written (DOS/runtime/input/loader)"
        checks = []
        if h in cls:
            checks.append("lockstep-R")
        if h in diff:
            checks.append("difftest")
        if not checks:
            checks.append("replay (unchecked)")
        c = stats.get(h, {}).get("count", 0)
        out.append("| `%s` | %s | %s | %d |" % (h, kind, ", ".join(checks), c))
    unseen = [f for f in fns if f not in fcount]
    out += ["", "## Translated routines", "",
            "%d routines are translated mechanically; their entry (stack depth) is compared against the original on every call of a lockstep run." % len(fns),
            "%d of them were entered by the runs given; **never entered** (%d): %s" % (len(fns) - len(unseen), len(unseen), ", ".join("`%s`" % f for f in unseen)), ""]
    print("\n".join(out))


def argparse_ns():
    import types
    return types.SimpleNamespace(run=None, replay=None)


if __name__ == "__main__":
    main()
