#!/usr/bin/env python3
"""portreport.py [out.md]: writes the list of hand-ported and not yet ported WL.EXE functions (docs/wl-port-status.md)."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..", "..", "..")
ports = {}
for l in open(os.path.join(here, "recomp", "ports.txt")):
    w = l.split("#")[0].split()
    if len(w) >= 2 and re.match(r"^[0-9A-Fa-f]+$", w[0]):
        ports[int(w[0], 16) & 0xFFFF] = w[1]
funcs = []
for l in open(os.path.join(root, "ida_scripts", "dump_callgraph.txt")):
    m = re.match(r"([0-9A-F]+) (\S+) (\d+) : ?(.*)", l)
    if m and int(m.group(1), 16) >= 0x10000:
        funcs.append((int(m.group(1), 16), m.group(2), int(m.group(3)), m.group(4).split()))
def area(a):
    a &= 0xFFFF
    if a < 0x1000: return "EGA blitters, mouse, title picture (driver)"
    if a < 0x1C00: return "start, file access, picture loading (platform)"
    if a < 0x6000: return "game logic: party, combat, map actions"
    if a < 0x7100: return "exploration: map view, movement, party groups"
    if a < 0x8E00: return "text engine and item records"
    if a < 0xA000: return "text window, hot keys, rosters (UI)"
    if a < 0xB000: return "map action handlers and item screens"
    return "character creation, menus, timers (UI / platform)"
done = [f for f in funcs if (f[0] & 0xFFFF) in ports]
todo = [f for f in funcs if (f[0] & 0xFFFF) not in ports]
out = ["# WL.EXE port status", "",
       "Generated by `engine/src/wasteland1/tools/portreport.py`. %d of %d functions are hand-ported (%d of %d code bytes)." %
       (len(done), len(funcs), sum(f[2] for f in done), sum(f[2] for f in funcs)), "",
       "## Ported", "", "| address | IDA name | C++ port | bytes |", "|---|---|---|---|"]
for a, n, s, _ in sorted(done):
    out.append("| %05X | %s | %s | %d |" % (a, n, ports[a & 0xFFFF], s))
out += ["", "## Not ported yet, by area", ""]
byarea = {}
for f in todo:
    byarea.setdefault(area(f[0]), []).append(f)
for k in sorted(byarea, key=lambda k: min(f[0] for f in byarea[k])):
    fs = sorted(byarea[k])
    out += ["### %s (%d functions, %d bytes)" % (k, len(fs), sum(f[2] for f in fs)), "",
            ", ".join("%05X %s (%d)" % (a, n, s) for a, n, s, _ in fs), ""]
open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "docs", "wl-port-status.md"), "w").write("\n".join(out) + "\n")
