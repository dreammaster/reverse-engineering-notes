"""
Function-level audit of the u5d decompilation against the original binaries.

Inputs:
  ida/out/<MOD>.json   function inventories produced by ida_scripts/export_functions.py
  u5d-main/src/*.c     decompiled sources (functions are named <MOD>_<hexoffset>[_Name])

Output: audit/function_audit.md and audit/function_audit.json.

A function counts as COVERED when a C definition with the matching module+offset
exists; it is flagged STUB / ASM when the lines directly above the definition say so
or when the body is only a debug() call.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
GAME_DIR = os.environ.get("U5_GAME_DIR", "C:/games/ultima5")
OUT = os.path.join(ROOT, "ida", "out")

# overlay -> C file prefix used in function names
OVERLAYS = ["BLCKTHRN", "CAST", "CAST2", "CMDS", "COMBAT", "COMSUBS", "DNGLOOK", "DUNGEON", "ENDGAME", "FLAMES",
            "FONT", "INTRO", "LOOKOBJ", "MAINOUT", "NPC", "OUTSUBS", "SHOPPES", "SHOPPES2", "SHOPPES3", "SJOG",
            "TALK", "TOWN", "ZSTATS"]
EXE_FILES = ["0000.c", "1000.c", "2000.c", "3000.c", "4000.c", "5000.c", "6000.c", "7000.c",
             "ultima.c", "vars.c", "grap_drv.c", "savegame.c", "translate.c", "font.c"]

NL = chr(10)
NAME_RE = re.compile(r"\b([A-Z][A-Z0-9]*)_([0-9a-f]{4})(?:_(\w+))?\s*\(")
DEF_RE = re.compile(r"^(?!\s)(?!//)(?!#)(?:static\s+|extern\s+|inline\s+)*[\w\s\*]*?\b([A-Za-z_]\w*)\s*\(([^;]*)$")
CRT_RE = re.compile(r"^//\s*([0-9a-f]{4})(?:\.\.([0-9a-f]{4}))?:\s*(.*)$")


def load_c_functions():
    """Returns {(module, offset): [info]} for every C definition whose name encodes an offset.

    The sources use Allman style: a definition is a column-0 line containing NAME( that does not
    end in ';', followed by a column-0 '{'; the body ends at the next column-0 '}'.
    """
    funcs = {}
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".c"):
            continue
        lines = open(os.path.join(SRC, fn), encoding="utf-8", errors="replace").read().splitlines()
        n = len(lines)
        i = 0
        while i < n:
            line = lines[i]
            nm = NAME_RE.search(line) if line and line[0] not in " 	/#{}" else None
            j = i
            if nm and not line.rstrip().endswith(";"):
                while j < n and j - i < 6 and "{" not in lines[j] and ";" not in lines[j]:
                    j += 1
            if nm and j < n and "{" in lines[j] and (j == i or ";" not in lines[j - 1]) and "=" not in line.split("(")[0]:
                k = j
                if not lines[j].rstrip().endswith("}"):
                    k = j + 1
                    while k < n and not lines[k].startswith("}"):
                        k += 1
                body = lines[i:k + 1]
                above = NL.join(lines[max(0, i - 4):i])
                text = NL.join(body)
                stub = bool(re.search(r"//\s*STUB", above))
                asm = bool(re.search(r"//\s*ASM", above))
                calls = sorted(set((mm.group(1), int(mm.group(2), 16)) for mm in NAME_RE.finditer(NL.join(body[1:]))))
                key = (nm.group(1), int(nm.group(2), 16))
                funcs.setdefault(key, []).append({"file": fn, "line": i + 1, "name": nm.group(0)[:-1].strip(), "lines": len(body),
                                                  "stub": stub, "asm": asm, "calls": calls, "static": line.startswith("static")})
                i = k
            i += 1
    return funcs


def load_crt_comments():
    """'// 017e: _astart' style comments in 0000.c documenting C runtime functions that are not decompiled."""
    out = {}
    for fn in ["0000.c"]:
        for line in open(os.path.join(SRC, fn), encoding="utf-8", errors="replace"):
            m = CRT_RE.match(line.strip())
            if m:
                out[int(m.group(1), 16)] = m.group(3)
    return out


def main():
    cfuncs = load_c_functions()
    crt = load_crt_comments()
    report = {}
    md = ["# Function audit: u5d vs original binaries\n",
          "Generated by `audit/audit_functions.py`. IDA inventory: prologue-seeded (`55 8B EC`) + call-target iteration.\n"]

    totals = dict(ida=0, covered=0, missing=0, stub=0, asm=0, extra=0)
    for mod in OVERLAYS + ["ULTIMA"]:
        js = json.load(open(os.path.join(OUT, mod + ".json")))
        base = 0x10000 if mod == "ULTIMA" else 0
        prefix = mod
        ida = {f["start"] - base: f for f in js["functions"]}
        cdef = {off: v for (p, off), v in cfuncs.items() if p == prefix}
        missing, stubs, asms = [], [], []
        covered = 0
        for off, f in sorted(ida.items()):
            if off in cdef:
                covered += 1
                info = cdef[off][0]
                if info["stub"]:
                    stubs.append((off, f["size"], info))
                elif info["asm"]:
                    asms.append((off, f["size"], info))
            elif mod == "ULTIMA" and off in crt:
                pass  # documented C-runtime function, intentionally provided by the host libc
            else:
                missing.append((off, f))
        crt_documented = sorted(o for o in ida if mod == "ULTIMA" and o in crt and o not in cdef)
        extra = sorted(o for o in cdef if o not in ida)
        r = dict(ida=len(ida), covered=covered, missing=[[o, f["size"], f["prologue"]] for o, f in missing],
                 stubs=[[o, s] for o, s, _ in stubs], asm=[[o, s] for o, s, _ in asms], extra=extra,
                 crt_documented=crt_documented)
        report[mod] = r
        totals["ida"] += len(ida)
        totals["covered"] += covered
        totals["missing"] += len(missing)
        totals["stub"] += len(stubs)
        totals["asm"] += len(asms)
        totals["extra"] += len(extra)

        md.append("\n## %s (%d functions in binary)\n" % (mod, len(ida)))
        md.append("- covered by a C definition: %d; C-runtime documented only: %d; **missing: %d**; stubs: %d; asm-style: %d; "
                  "C functions with no binary match: %d\n" % (covered, len(crt_documented), len(missing), len(stubs), len(asms), len(extra)))
        if missing:
            md.append("\n| offset | size | std prologue | note |\n|---|---|---|---|\n")
            for o, f in missing:
                md.append("| %04x | %d | %s | |\n" % (o, f["size"], "yes" if f["prologue"] else "no"))
        if stubs:
            md.append("\nStubbed: " + ", ".join("%04x(%d B, %s)" % (o, s, i["name"]) for o, s, i in stubs) + "\n")
        if extra:
            md.append("\nC definitions with no matching binary function start: " + ", ".join("%04x" % o for o in extra) + "\n")

    md.insert(2, "\n**Totals:** %s\n" % json.dumps(totals))
    os.makedirs(os.path.join(ROOT, "audit"), exist_ok=True)
    open(os.path.join(ROOT, "audit", "function_audit.md"), "w").write("".join(md))
    json.dump(report, open(os.path.join(ROOT, "audit", "function_audit.json"), "w"), indent=1)
    print(json.dumps(totals))
    for mod, r in report.items():
        print("%-10s ida=%3d covered=%3d missing=%3d stub=%d asm=%d extra=%d crt=%d" % (
            mod, r["ida"], r["covered"], len(r["missing"]), len(r["stubs"]), len(r["asm"]), len(r["extra"]), len(r["crt_documented"])))


if __name__ == "__main__":
    main()
