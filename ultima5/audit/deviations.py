"""
Catalogue of every place where the modern (non-DOS16) build deliberately differs from the original IBM 1.16 code:
preprocessor blocks conditioned on TARGET_DOS16 / MATCHING_BUILD / GOG_BUILD / ENABLE_* / RELEASE_BUILD, plus source
comments that mark known original bugs ("BUG", "sic") or code taken from the FM Towns version ("FMT").

For a ScummVM port these are the behaviours to decide on one by one: reproduce the original, keep the fix, or make it
an option.  Writes audit/deviations.md.
"""
import os
import re

import audit_functions as a

COND_RE = re.compile(r"^\s*#\s*(if|ifdef|ifndef|elif)\b(.*)$")
INTEREST = re.compile(r"TARGET_DOS16|MATCHING_BUILD|GOG_BUILD|ENABLE_[A-Z_]+|RELEASE_BUILD|TARGET_SDL|BACKEND_")
NOTE_RE = re.compile(r"//.*\b(BUG|BUGFIX|sic|FMT|NOT MATCHING|STUB)\b")


def scan():
    blocks, notes = [], []
    for fn in sorted(os.listdir(a.SRC)):
        if not fn.endswith(".c"):
            continue
        lines = open(os.path.join(a.SRC, fn), encoding="utf-8", errors="replace").read().splitlines()
        stack = []
        for i, line in enumerate(lines):
            m = COND_RE.match(line)
            if m:
                kind, cond = m.group(1), m.group(2).strip()
                if kind == "elif":
                    if stack:
                        stack[-1][1] = cond
                    continue
                stack.append([i + 1, cond, kind, None])
                continue
            if re.match(r"^\s*#\s*else\b", line) and stack:
                stack[-1][3] = i + 1
                continue
            if re.match(r"^\s*#\s*endif\b", line) and stack:
                start, cond, kind, els = stack.pop()
                if INTEREST.search(cond):
                    blocks.append((fn, start, i + 1, ("#%s %s" % (kind, cond)).strip(), els))
                continue
            n = NOTE_RE.search(line)
            if n:
                notes.append((fn, i + 1, n.group(1), line.strip()[:110]))
    return blocks, notes


def main():
    blocks, notes = scan()
    md = ["# Deviations from the original code\n\n",
          "Generated by `audit/deviations.py`. The `if !defined(TARGET_DOS16)` blocks are what the original (IBM 1.16, DOS) "
          "does *not* contain; `MATCHING_BUILD` blocks are original-only.\n\n",
          "## Conditional blocks (%d)\n\n| file | lines | condition | has #else |\n|---|---|---|---|\n" % len(blocks)]
    for fn, s, e, cond, els in blocks:
        md.append("| %s | %d-%d | `%s` | %s |\n" % (fn, s, e, cond, "yes" if els else ""))
    md.append("\n## Source annotations (%d)\n\n| file | line | tag | text |\n|---|---|---|---|\n" % len(notes))
    for fn, ln, tag, text in notes:
        md.append("| %s | %d | %s | `%s` |\n" % (fn, ln, tag, text.replace("|", "/")))
    open(os.path.join(a.ROOT, "audit", "deviations.md"), "w").write("".join(md))
    print("deviations: %d conditional blocks, %d annotations" % (len(blocks), len(notes)))


if __name__ == "__main__":
    main()
