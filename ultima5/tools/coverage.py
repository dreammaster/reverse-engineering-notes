"""
Function coverage of the scripted scenarios.

    mingw32-make COVERAGE=1
    set U5_EXE=build-cov/u5.exe  &&  python tools/smoke_test.py      (any scenarios; .gcda files accumulate)
    python tools/coverage.py                                         -> audit/coverage.md

Reads gcov's per-function summaries for src/ and lists, per source file, the functions that never ran and the share of
lines executed, so new scenarios/fixtures can be aimed at the gaps.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "build-cov")


def main():
    results = {}  # file -> {func: (pct, lines)}
    for dirpath, _, files in os.walk(BUILD):
        for f in files:
            if not f.endswith(".gcda"):
                continue
            out = subprocess.run(["gcov", "-f", "-n", "-o", dirpath, os.path.join(dirpath, f)], capture_output=True, text=True,
                                 cwd=ROOT).stdout
            cur = None
            funcs = {}
            src = None
            for line in out.splitlines():
                m = re.match(r"Function '(.+)'", line)
                if m:
                    cur = m.group(1)
                    continue
                m = re.match(r"Lines executed:([\d.]+)% of (\d+)", line)
                if m and cur:
                    funcs[cur] = (float(m.group(1)), int(m.group(2)))
                    cur = None
                    continue
                m = re.match(r"File '(.+)'", line)
                if m:
                    src = m.group(1)
            if src:
                norm = src.replace("\\", "/")
                if norm.startswith("src/") or "/src/" in norm:
                    results.setdefault(norm.split("src/", 1)[-1], {}).update(funcs)

    tot = ran = lines = linesran = 0
    md = ["# Scenario coverage (gcov)\n\nGenerated by `tools/coverage.py` from the `smoke_test.py` scenarios; functions that never "
          "executed are listed.  Backend/DOS-only files are excluded from the totals.\n\n"]
    rows = []
    for f in sorted(results):
        if re.search(r"(sdl|dos|vga|cdda|adl|spk)\.c$", f):
            continue
        fn = results[f]
        never = sorted(k for k, (p, n) in fn.items() if p == 0.0)
        n_lines = sum(n for p, n in fn.values())
        n_ran = sum(p * n / 100.0 for p, n in fn.values())
        tot += len(fn)
        ran += len(fn) - len(never)
        lines += n_lines
        linesran += n_ran
        rows.append((f, len(fn), len(never), n_lines, n_ran, never))
    md.append("**Functions run: %d of %d (%.0f%%); lines executed: %.0f%%.**\n\n" % (ran, tot, 100.0 * ran / tot, 100.0 * linesran / lines))
    md.append("| file | functions | never run | lines run |\n|---|---|---|---|\n")
    for f, n, nv, nl, nr, never in rows:
        md.append("| %s | %d | %d | %.0f%% |\n" % (f, n, nv, 100.0 * nr / nl if nl else 0))
    md.append("\n## Functions never run\n\n")
    for f, n, nv, nl, nr, never in rows:
        if never:
            md.append("* **%s**: %s\n" % (f, ", ".join("`%s`" % k for k in never)))
    open(os.path.join(ROOT, "audit", "coverage.md"), "w").write("".join(md))
    print("functions run %d/%d, lines %.0f%%" % (ran, tot, 100.0 * linesran / lines))


if __name__ == "__main__":
    main()
