#!/usr/bin/env python3
"""Generates xanth/tables/vars.h and vars_init.inc: the game's mutable state outside the object records, as one struct of named members.

    python tools/gen_vars.py <image.bin> <xanth_save_regions.tsv> <output dir>

The original saves 205 regions of its data (4,522 bytes: story flags, the conversation line flags, the clock, the score ...). Each region becomes a member of
`Xanth::Vars` (bytes and words by name, larger regions as byte arrays); `kVarRegions` lists the regions in the original's save order with the member's offset,
size and the original address, which the comparison tools use to line a dump of the original's data segment up with the engine's state. Two regions of the original
cover the same address (a flag it saves twice): they share one member. The initial values (a new game) are read from the executable image.
"""
import csv
import sys


def main():
    image = open(sys.argv[1], "rb").read()
    rows = list(csv.DictReader(open(sys.argv[2], encoding="utf-8"), delimiter="\t"))
    outdir = sys.argv[3]

    members = []                      # unique by address, in order of first appearance
    by_addr = {}
    for r in rows:
        addr, size = int(r["address"], 16), int(r["size"])
        if addr in by_addr:
            assert by_addr[addr]["size"] == size, "region at %x saved with two sizes" % addr
            continue
        m = {"name": r["name"], "addr": addr, "size": size}
        by_addr[addr] = m
        members.append(m)
    assert len({m["name"] for m in members}) == len(members), "member names are unique"

    h = []
    h.append("// generated by tools/gen_vars.py from the analysis database - do not edit. Structure only: no game text.")
    h.append("#ifndef XANTH_TABLES_VARS_H")
    h.append("#define XANTH_TABLES_VARS_H")
    h.append("")
    h.append('#include "common/types.h"')
    h.append("")
    h.append("namespace Xanth {")
    h.append("")
    h.append("// The game state outside the object records: one member per region of the original's save game (names from reversing/analysis/xanth_flags.tsv).")
    h.append("struct Vars {")
    for m in members:
        if m["size"] == 1:
            h.append("\tuint8 %s;" % m["name"])
        elif m["size"] == 2:
            h.append("\tuint16 %s;" % m["name"])
        else:
            h.append("\tuint8 %s[%d];" % (m["name"], m["size"]))
    h.append("};")
    h.append("")
    h.append("struct VarRegion {")
    h.append("\tconst char *name;")
    h.append("\tunsigned offset;          // of the member in Vars")
    h.append("\tunsigned size;")
    h.append("\tunsigned address;         // linear address in the original's memory image")
    h.append("};")
    h.append("")
    h.append("struct VarMember {")
    h.append("	unsigned offset;          // in Vars")
    h.append("	unsigned size;")
    h.append("};")
    h.append("")
    h.append("extern const VarRegion kVarRegions[%d];     // in the original's save order" % len(rows))
    h.append("extern const VarMember kVarMembers[%d];     // every member of Vars once, in declaration order" % len(members))
    h.append("extern const unsigned char kVarsInitial[];   // initial values: the members' bytes concatenated in the order of kVarMembers")
    h.append("")
    h.append("} // namespace Xanth")
    h.append("")
    h.append("#endif")
    open(outdir + "/vars.h", "w", newline="\n").write("\n".join(h) + "\n")

    c = []
    c.append("// generated by tools/gen_vars.py from the analysis database - do not edit. Structure only: no game text.")
    c.append('#include "xanth/tables/vars.h"')
    c.append("")
    c.append("#include <cstddef>")
    c.append("")
    c.append("namespace Xanth {")
    c.append("")
    c.append("const VarRegion kVarRegions[%d] = {" % len(rows))
    for r in rows:
        addr, size = int(r["address"], 16), int(r["size"])
        c.append('\t{"%s", (unsigned)offsetof(Vars, %s), %d, 0x%X},' % (by_addr[addr]["name"], by_addr[addr]["name"], size, addr))
    c.append("};")
    c.append("")
    c.append("const VarMember kVarMembers[%d] = {" % len(members))
    for m in members:
        c.append("	{(unsigned)offsetof(Vars, %s), %d}," % (m["name"], m["size"]))
    c.append("};")
    c.append("")
    values = []
    for m in members:
        values.extend(image[m["addr"]:m["addr"] + m["size"]])
    c.append("const unsigned char kVarsInitial[] = {")
    for i in range(0, len(values), 32):
        c.append("\t" + ", ".join(str(v) for v in values[i:i + 32]) + ",")
    c.append("};")
    c.append("")
    c.append("} // namespace Xanth")
    open(outdir + "/vars.cpp", "w", newline="\n").write("\n".join(c) + "\n")
    print("regions %d, members %d, bytes %d" % (len(rows), len(members), len(values)))


if __name__ == "__main__":
    main()
