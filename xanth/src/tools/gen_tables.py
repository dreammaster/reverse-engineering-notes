#!/usr/bin/env python3
"""Generates xanth/tables/*.inc from the analysis database: structure compiled into the original executable (object records, per-type table,
attribute descriptors ...). Only numbers are written - never game text.

    python tools/gen_tables.py <image.bin> <xanth_objects.tsv> <output dir>

image.bin is the flat memory image of the executable written by reversing/scripts/dump_image.py (linear address = segment * 16 + offset).
"""
import csv
import struct
import sys

SEG_OBJECT_TABLES = 0x33A10          # seg_8A9E4 = seg_8A9E6 = seg_8A9E8 = 0x33A1: base of the object type table and the attribute descriptors
ATTR_DESCRIPTORS = 0x33A1C           # 4 bytes per attribute id: {u8 bitOffset; u8 pad; u16 typeMask}; id 0 overlaps the type table
ATTR_COUNT = 24                      # ids 1..24 (24 has an empty mask)


def array(name, ctype, values, per_line=16, comment=""):
    out = []
    if comment:
        out.append("// " + comment)
    out.append("static const %s %s[] = {" % (ctype, name))
    for i in range(0, len(values), per_line):
        out.append("\t" + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    image = open(sys.argv[1], "rb").read()
    objects = list(csv.DictReader(open(sys.argv[2], encoding="utf-8"), delimiter="\t"))
    outdir = sys.argv[3]

    # per-type table at 0x33A10: 3 bytes per type {u8 flags (meaning not identified); u8 listSlots; u8 recordSize}
    types = []
    for t in range(1, 6):
        a = SEG_OBJECT_TABLES + (t - 1) * 3
        types.append(tuple(image[a:a + 3]))

    attrs = [(0, 0, 0)]
    for i in range(1, ATTR_COUNT + 1):
        a = ATTR_DESCRIPTORS + 4 * i
        attrs.append((image[a], image[a + 1], struct.unpack("<H", image[a + 2:a + 4])[0]))

    count = len(objects)
    types_of, offsets, blob = [0], [0], []
    for o in objects:
        rec = bytes.fromhex(o["record_hex"])
        t = int(o["type"])
        assert len(rec) == types[t - 1][2], "record size of object %s" % o["id"]
        assert int(o["id"]) == len(types_of), "object ids are consecutive"
        types_of.append(t)
        offsets.append(len(blob))
        blob.extend(rec)

    text = "// generated by tools/gen_tables.py from the analysis database - do not edit. Structure only: no game text.\n\n"
    text += "static const int kObjectCount = %d;       // ids 1..kObjectCount\n\n" % count
    text += "// per object type 1..5 (room, item, container, prop, character): {flags (meaning not identified), child list slots, record size in bytes}\n"
    text += "static const unsigned char kObjectTypeTable[5][3] = {\n" + "".join("\t{%d, %d, %d},\n" % t for t in types) + "};\n\n"
    text += "// attribute descriptors by id (0 unused): {bit offset in the record data (record + 4), unused, mask of the object types that have the attribute (bit type-1)}\n"
    text += "static const unsigned short kAttributeBit[] = {%s};\n" % ", ".join(str(a[0]) for a in attrs)
    text += "static const unsigned short kAttributeTypes[] = {%s};\n\n" % ", ".join(str(a[2]) for a in attrs)
    text += array("kObjectType", "unsigned char", types_of, comment="type of every object (index 0 unused)")
    text += "\n" + array("kObjectRecordOffset", "unsigned short", offsets, comment="offset of every object's initial record in kObjectRecords")
    text += "\n" + array("kObjectRecords", "unsigned char", blob, per_line=32, comment="initial records of all objects (the state of a new game), concatenated")
    open(outdir + "/object_tables.inc", "w", newline="\n").write(text)
    print("objects %d, record bytes %d, attributes %d" % (count, len(blob), len(attrs) - 1))


if __name__ == "__main__":
    main()
