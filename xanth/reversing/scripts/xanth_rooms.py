"""
Joins the object, exit, music, picture and scene tables into one per-room dossier: analysis/xanth_rooms.md.
For each of the 70 rooms: id and name, picture, music, exits, hotspot count, handler number and the objects that start in it.

    python xanth_rooms.py
"""
import collections
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
A = os.path.join(HERE, "..", "analysis")


def rd(name):
    return list(csv.DictReader(open(os.path.join(A, name), encoding="utf-8", newline=""), delimiter="\t"))


objs = rd("xanth_objects.tsv")
byid = {int(o["id"]): o for o in objs}
rooms = [o for o in objs if o["type"] == "1"]
exits = collections.defaultdict(list)
for e in rd("xanth_exits.tsv"):
    exits[int(e["room"])].append(e)
music = {int(r["room"]): r for r in rd("xanth_room_music.tsv")}
pics = {int(r["room"]): r for r in rd("xanth_room_pics.tsv")}
spots = collections.Counter(int(r["room"]) for r in rd("xanth_scenes.tsv"))
contents = collections.defaultdict(list)
for o in objs:
    if o["type"] != "1" and o["location"].isdigit():
        contents[int(o["location"])].append(o)

with open(os.path.join(A, "xanth_rooms.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# Companions of Xanth: room dossier\n\nGenerated by `scripts/xanth_rooms.py` from the object, exit, music, picture and scene tables.\n"
            "Contents are the objects whose initial location is the room (carried items and nested containers appear under their holder).\n")
    for r in sorted(rooms, key=lambda o: int(o["id"])):
        rid = int(r["id"])
        f.write("\n## %d %s\n\n" % (rid, r["name"]))
        p, m = pics.get(rid), music.get(rid)
        f.write("- picture: %s\n" % ("%s entry %s (picNum %s)" % (p["pic_file"], p["entry"], p["picNum"]) if p else "none"))
        f.write("- music: %s\n" % ("%s tune %s" % (m["mus_file"], m["tune"]) if m else "none"))
        f.write("- hotspots: %d, handler objh_%03d\n" % (spots.get(rid, 0), int(r["handler"] or 0)))
        ex = exits.get(rid, [])
        if ex:
            f.write("- exits: " + ", ".join("%s -> %s%s" % (e["direction"], e["target_name"] or e["target"], " (door %s)" % byid[int(e["door_object"])]["name"] if e["door_object"].isdigit() and int(e["door_object"]) in byid else "") for e in ex) + "\n")
        c = contents.get(rid, [])
        if c:
            f.write("- contents: " + ", ".join("%s (%s)" % (o["name"], o["id"]) for o in c) + "\n")
print("rooms", len(rooms))
