def load_vars():
    """members of Xanth::Vars (the saved variables) with their C++ types"""
    out = {}
    for line in open(os.path.join(SRC, "xanth", "tables", "vars.h"), encoding="utf-8"):
        m = re.match(r"^\s+(uint8|uint16)\s+(\w+)(\[(\d+)\])?;", line)
        if m:
            out[m.group(2)] = (m.group(1), int(m.group(4)) if m.group(4) else 0)
    return out


def logic_name(n):
    """C++ name of a function of the original"""
    n = n.rstrip("?")
    if n.startswith("j_"):
        n = n[2:]
    return re.sub(r"[^A-Za-z0-9_]", "_", n)


class LogicNames(Names):
    def __init__(self, ctx, vars_, generated):
        self.ctx = ctx
        self.vars = vars_
        self.generated = generated    # C++ names of the functions that get generated
        self.rt = {}                  # runtime globals: name -> size
        self.calls = {}               # routines reached through Game: name -> max argument count
        self.estr = {}                # program text -> index
        self.sig = {}                 # generated function -> (return type, parameter count)
        self.cur = None
        for n in CORE:
            self.rt[n] = 2

    def glob(self, name, disp, size):
        name = self.ident(name)
        if name in self.vars:
            ty, n = self.vars[name]
            base = "v." + name
            if n:
                return base + "[%d]" % disp
            if disp:
                return "v.%s_hi" % name
            if size == 1 and ty == "uint16":
                return "(v.%s & 0xFF)" % name
            return base
        key = name + ("_hi" if disp else "")
        self.rt[key] = max(self.rt.get(key, 0), size or 2)
        if name in self.ctx.arrays:
            return "rt.%s[%d]" % (name, disp) if disp else "rt." + name
        return "rt." + key

    def loc(self, func, name, disp, size):
        m = re.match(r"^bp([+-]\d+)$", name)
        if m:
            off = int(m.group(1))
            name = "var_%X" % -off if off < 0 else "arg_%X" % (off - 6)
        n = {"arg_0": "arg0", "arg_2": "arg1", "arg_4": "arg2", "arg_6": "arg3", "arg_8": "arg4"}.get(name, name)
        n = re.sub(r"^var_", "v", n)
        if disp:
            return "%s_hi" % n
        return n

    def func(self, name):
        return logic_name(STUBS.get(name, name))

    def returns_far(self, name):
        return name.startswith("conv_text") or name == "number_to_words" or logic_name(name) in getattr(self, "namecb", ())

    def min_params(self, name):
        want = logic_name(name)
        best = 2 if want in getattr(self, "namecb", ()) else 0
        for k, v in CALLSIG.items():
            if logic_name(STUBS.get(k, k)) == want:
                best = max(best, max(v))
        return best

    def call(self, tgt, args):
        n = self.func(tgt)
        if n in CLIB:
            return "%s(%s)" % (n, ", ".join(args))
        if n in self.generated:
            return "%s(%s)" % (n, ", ".join(["g"] + args))
        self.calls[n] = max(self.calls.get(n, 0), len(args))
        return "g.%s(%s)" % (n, ", ".join(args))

    def header(self, name, params):
        ret = "TextRef " if self.returns_far(name) else "int "
        self.sig[name] = (ret, len(params))
        return "%s%s(%s)" % (ret, logic_name(name), ", ".join(["Game &g"] + ["Word " + p for p in params]))

    def prolog(self):
        return ["Vars &v = g.state.v;", "Runtime &rt = g.rt;"]

    def kstring(self, off):
        t = self.ctx.dseg_string(off)
        if t is None:
            return "DSEG(0x%X)" % off
        return self.es(t)

    def es(self, t):
        if t not in self.estr:
            self.estr[t] = len(self.estr)
        return "ES(%d)" % self.estr[t]

    def msg(self, block, index):
        return "MSG(%d, %d)" % (block, index)

    def addr(self, sym):
        if sym in self.ctx.strings:
            return self.string(sym)
        if sym in self.ctx.procs:
            return "FN(%s)" % logic_name(sym)
        n = self.ident(sym)
        self.rt[n] = max(self.rt.get(n, 0), 1)
        return "rt." + n if sym in self.ctx.arrays else "(intptr_t)&rt." + n

    def string(self, sym):
        """text that is part of the program (not of the message file) is kept out of the generated source: ES(n) is an index into engine_strings.inc"""
        t = self.ctx.strings.get(sym)
        if t is None:
            if sym in self.ctx.procs:
                return "FN(%s), 0" % logic_name(sym)      # a callback is a far pointer: two words
            return self.addr(sym)           # not text: a buffer or other data the original passes by address
        return self.es(t)


def argc(ctx, name):
    return sum(1 for k in ctx.locs.get(name, {}) if k.startswith("arg_"))


def write(path, text):
    with open(path, "w", encoding="utf-8", newline=NL) as fh:
        fh.write(text)


UI_CALLEE = re.compile(r"^(Image_|Screen_|Windows_|Font_(?!WriteMessage|WriteLines2)|Mouse|MouseCursor_|Palette_|Events_|DialogBtn_|Gfx_|pic_|vga_|Picture|PicFile|load_pic|sub_2[0-9A-F]{4}$|wputchar|show_text_box|Conversation_Show|realsound|voc_|mus_|memAlloc|Memory_|set_mouse|disable_pic|setup_pic|overlay|RoomItem_|popup_|game_over|new_handle|rtlink_)")


def stub_targets(ctx):
    """overlay entry points (`call rtlink_thunk / jmp target`): stub name -> target routine"""
    out = {}
    for n, e in ctx.procs.items():
        i = e
        if i + 1 < len(ctx.insns) and ctx.insns[i].mn == "call" and ctx.insns[i].ops and G.STRIP.sub("", ctx.insns[i].ops[0].strip()) == "rtlink_thunk" and ctx.insns[i + 1].mn == "jmp":
            out[n] = G.STRIP.sub("", ctx.insns[i + 1].ops[0].strip())
    return out


def is_logic(ctx, target):
    """a routine that is game logic rather than drawing: small, and it calls none of the drawing / device routines"""
    if target not in ctx.procs or re.match(r"^(j_)?_", target):       # C runtime routines are not game logic
        return False
    idxs = G.L.reachable(ctx.insns, ctx.labels, ctx.tables, ctx.procs[target])
    if len(idxs) > 250:
        return False
    for i in idxs:
        x = ctx.insns[i]
        if x.mn == "call" and x.ops:
            c = G.STRIP.sub("", x.ops[0].strip())
            if UI_CALLEE.match(c.rstrip("?")):
                return False
    return True


def name_callbacks(ctx):
    """the 49 objects whose name comes from a callback: (object id, target routine)"""
    lines = open(os.path.join(HERE, "..", "..", "xanth.asm"), encoding="utf-8", errors="replace").read().split(NL)
    i = [k for k, l in enumerate(lines) if l.startswith("off_34E52")][0]
    cur, out = [], []
    k = i - 3
    while not lines[k].startswith("off_34F84"):
        m = re.match(r"^" + BS + "s*(?:" + BS + "w+" + BS + "s+)?db" + BS + "s+([0-9A-Fa-f]+h?)", lines[k])
        d = re.match(r"^" + BS + "s*(?:" + BS + "w+" + BS + "s+)?dd" + BS + "s+(" + BS + "w+)", lines[k])
        if m and not d:
            v = m.group(1)
            cur.append(int(v[:-1], 16) if v.lower().endswith("h") else int(v))
        elif d and len(cur) >= 2:
            out.append((cur[-2] | (cur[-1] << 8), d.group(1)))
            cur = []
        k += 1
    res = []
    for obj, stub in out:
        idx = ctx.procs.get(stub, ctx.labels.get(stub))
        tgt = None
        if idx is not None and ctx.insns[idx].mn == "call" and G.STRIP.sub("", ctx.insns[idx].ops[0].strip()) == "rtlink_thunk":
            nx = ctx.insns[idx + 1]
            if nx.mn == "jmp":
                tgt = G.STRIP.sub("", nx.ops[0].strip())
        res.append((obj, tgt or stub))
    return res


def enum_values(prefix):
    out = {}
    for line in open(os.path.join(HERE, "..", "analysis", "xanth_enums.tsv"), encoding="utf-8"):
        p = line.rstrip(NL).split(TAB)
        if len(p) == 3 and p[0] == prefix:
            out[p[2]] = int(p[1])
    return out


def main():
    args = [a for a in sys.argv[1:] if a != "--all"]
    out_dir = os.path.join(SRC, "xanth", "logic")
    if "--out" in args:
        i = args.index("--out")
        out_dir = args[i + 1]
        del args[i:i + 2]
    ctx = G.Ctx()
    stubs_all = stub_targets(ctx)
    for stub, tgt in stubs_all.items():
        if stub not in STUBS and tgt != stub and is_logic(ctx, tgt) and not FAMILY.match(stub) and not re.match(r"^(objh|exit_fn|event_fn|conv_cb|conv_text|cmd)", stub):
            STUBS[stub] = tgt
    namecb = name_callbacks(ctx)
    todo = args or sorted(n for n in ctx.procs if FAMILY.match(n)) + [n for n in ENGINE_LOGIC if n in ctx.procs] + sorted({t for _, t in namecb if t in ctx.procs}) + sorted({t for st, t in STUBS.items() if t in ctx.procs and t not in ENGINE_LOGIC and not FAMILY.match(t) and logic_name(t) not in HAND and is_logic(ctx, t)})
    todo = list(dict.fromkeys(todo))
    if not args:
        # the small helpers the generated logic calls (and that call no drawing routine) are logic too
        seen = {logic_name(n) for n in todo}
        queue = list(todo)
        while queue:
            n = queue.pop()
            for i in G.L.reachable(ctx.insns, ctx.labels, ctx.tables, ctx.procs[n]):
                x = ctx.insns[i]
                for o in x.ops:
                    mo = re.match(r"^offset\s+([A-Za-z_][\w?]*)$", o.strip())
                    if mo and mo.group(1) in ctx.procs and x.mn != "call":       # a routine passed as a callback
                        cb = mo.group(1)
                        lcb = logic_name(cb)
                        if lcb not in seen and lcb not in HAND and lcb not in CLIB and is_logic(ctx, cb):
                            seen.add(lcb)
                            todo.append(cb)
                            queue.append(cb)
                if x.mn != "call" or not x.ops:
                    continue
                c = G.STRIP.sub("", x.ops[0].strip())
                c = STUBS.get(c, c)
                ln = logic_name(c)
                if c in ctx.procs and ln not in seen and ln not in HAND and ln not in CLIB and not re.match(r"^(rtlink|loc_)", c) and is_logic(ctx, c):
                    seen.add(ln)
                    todo.append(c)
                    queue.append(c)
    generated = {logic_name(n) for n in todo}
    names = LogicNames(ctx, load_vars(), generated)
    names.namecb = {logic_name(t) for _, t in namecb}
    os.makedirs(out_dir, exist_ok=True)
    ok, bad, chunks = [], {}, {}
    manual = {}
    mp = os.path.join(HERE, "..", "analysis", "xanth_logic_manual.tsv")
    if os.path.exists(mp) and "--all" not in sys.argv:
        for line in open(mp, encoding="utf-8"):
            p = line.rstrip(NL).split(TAB)
            if len(p) >= 2:
                manual[p[0]] = p[1]
    for n in todo:
        if logic_name(n) in manual:
            bad[n] = "does not compile yet: " + manual[logic_name(n)]
            continue
        try:
            names.cur = n
            t = function_text(ctx, n, names)
        except Exception as e:
            bad[n] = str(e)[:100]
            continue
        ok.append(n)
        fam = "cmd" if n.startswith("cmd") else re.sub(r"_?\d+$", "", n) if FAMILY.match(n) else "engine"
        chunks.setdefault(fam, []).append(t)
    print(len(ok), "functions,", len(bad), "failed")
    if args:
        for fam, ts in chunks.items():
            print(NL.join(ts))
        for n, e in bad.items():
            print("FAILED", n, e)
        return
    for fam, ts in chunks.items():
        step = 80 if fam == "objh" else 1000
        for k in range(0, len(ts), step):
            fn = "%s%s.cpp" % (fam, "_%02d" % (k // step) if len(ts) > step else "")
            body = (NL + NL).join(ts[k:k + step])
            write(os.path.join(out_dir, fn), HDR + NL + '#include "xanth/logic/logic.h"' + NL + NL + "namespace Xanth {" + NL + NL + body + NL + NL + "} // namespace Xanth" + NL)
    # declarations; the functions that could not be generated are declared too and stubbed so that the tables link
    decl = [HDR]
    for n in sorted(todo):
        ret, k = names.sig.get(n, ("TextRef " if n.startswith("conv_text") or n == "number_to_words" or logic_name(n) in names.namecb else "int ", max(argc(ctx, n), names.min_params(n))))
        decl.append("%s%s(Game &g%s);%s" % (ret, logic_name(n), "".join(", Word a%d" % i for i in range(k)), "  // not decompiled" if n in bad else ""))
    write(os.path.join(out_dir, "functions.inc"), NL.join(decl) + NL)
    stubs = [HDR, '#include "xanth/logic/logic.h"', "", "namespace Xanth {", "", "// Functions the decompiler could not translate yet; until a hand-written replacement exists they do nothing."]
    for n in sorted(bad):
        params = ", ".join(["Game &"] + ["Word"] * argc(ctx, n))
        ret, k = names.sig.get(n, ("TextRef " if n.startswith("conv_text") or n == "number_to_words" or logic_name(n) in names.namecb else "int ", max(argc(ctx, n), names.min_params(n))))
        params = ", ".join(["Game &"] + ["Word"] * k)
        stubs.append("%s%s(%s) { return %s; }  // %s" % (ret, logic_name(n), params, "TextRef()" if ret.startswith("TextRef") else "0", bad[n]))
    stubs.append("")
    stubs.append("} // namespace Xanth")
    write(os.path.join(out_dir, "not_decompiled.cpp"), NL.join(stubs) + NL)
    decls, inits = [HDR], [HDR]
    doff = {}
    for line in open(os.path.join(HERE, "..", "..", "engine", "host", "gen", "lifted_data.h"), encoding="utf-8", errors="replace"):
        m = re.match(r"constexpr uint16_t D_(\w+) = (0x[0-9A-Fa-f]+);", line)
        if m:
            doff[m.group(1)] = int(m.group(2), 16)
    for n, sz in sorted(names.rt.items()):
        base = n[:-3] if n.endswith("_hi") and n[:-3] in ctx.arrays else n
        if base in ctx.arrays:
            es, cnt = ctx.arrays[base]
            if base == n:
                decls.append("char %s[%d];" % (n, es * cnt))
            continue
        kind = ctx.kinds.get(n)
        width = {"db": 1, "dw": 2, "dd": 4}.get(kind, sz)
        decls.append("%s %s;" % ({1: "uint8", 2: "uint16", 4: "uint32"}[width], n))
        if n in doff and ctx.image:
            val = int.from_bytes(ctx.image[ctx.DSEG + doff[n]:ctx.DSEG + doff[n] + width], "little")
            if val:
                inits.append("		rt.%s = %d;" % (n, val))
    write(os.path.join(out_dir, "runtime_vars.inc"), NL.join(decls) + NL)
    write(os.path.join(out_dir, "runtime_init.inc"), NL.join(inits).replace("		", TAB + TAB) + NL)
    other = [HDR]
    for n, c in sorted(names.calls.items()):
        if n in HAND:
            continue
        k = max(1, min(c, 5))
        other.append("int %s(%s) { return other(%s%s); }" % (n, ", ".join("Word a%d = 0" % i for i in range(k)), '"%s"' % n, "".join(", a%d" % i for i in range(k))))
    write(os.path.join(out_dir, "engine_other.inc"), NL.join(other) + NL)
    write(os.path.join(out_dir, "engine_calls.txt"), "".join("%s%s%d%s" % (n, TAB, c, NL) for n, c in sorted(names.calls.items())))
    write(os.path.join(out_dir, "failed.txt"), "".join("%s%s%s%s" % (n, TAB, e, NL) for n, e in sorted(bad.items())))
    lines = ["// generated by reversing/scripts/gen_logic.py - the text of the original program that the logic prints; local only, not committed"]
    for t, i in sorted(names.estr.items(), key=lambda kv: kv[1]):
        lines.append("/* %d */ %s," % (i, '"' + t.replace(BS, BS + BS).replace('"', BS + '"') + '"'))
    write(os.path.join(out_dir, "engine_strings.inc"), NL.join(lines) + NL)
    # the tables the logic indexes through segment variables (static data of the original program, linear 0x31550-0x33FFF)
    if ctx.image:
        lo, hi = 0x31550, 0x34000
        data = ctx.image[lo:hi]
        rows = [HDR.replace("Game", "game") + " Static tables of the original program that the logic reads by segment:offset (linear %05X-%05X)." % (lo, hi)]
        for i in range(0, len(data), 24):
            rows.append(",".join("0x%02X" % c for c in data[i:i + 24]) + ",")
        write(os.path.join(out_dir, "exe_tables.inc"), NL.join(rows) + NL)
    # the data segment's initial contents: static tables the logic indexes by pointer (mem16(DS, ...))
    if ctx.image:
        data = ctx.image[ctx.DSEG:ctx.DSEG + 0x6000]
        rows = [HDR + " Initial contents of the original's data segment (first 0x6000 bytes), for the tables the logic indexes by pointer."]
        for i in range(0, len(data), 24):
            rows.append(",".join("0x%02X" % c for c in data[i:i + 24]) + ",")
        write(os.path.join(out_dir, "exe_dseg.inc"), NL.join(rows) + NL)
    # dispatch tables
    cmds = enum_values("CMD")
    write(os.path.join(out_dir, "commands.h"), HDR + NL + "#ifndef XANTH_LOGIC_COMMANDS_H" + NL + "#define XANTH_LOGIC_COMMANDS_H" + NL + NL + "namespace Xanth {" + NL + NL + "enum Command {" + NL +
          "".join("%s%s = %d,%s" % (TAB, k, v, NL) for k, v in sorted(cmds.items(), key=lambda kv: kv[1])) + "};" + NL + NL + "} // namespace Xanth" + NL + NL + "#endif" + NL)
    wh = []
    for m in re.finditer(r"WORD_HANDLER <(\w+), j_(\w+)>", open(os.path.join(HERE, "..", "..", "xanth.asm"), encoding="utf-8", errors="replace").read()):
        wh.append((m.group(1), m.group(2)))
    t = [HDR, '#include "xanth/logic/logic.h"', '#include "xanth/logic/commands.h"', "", "namespace Xanth {", ""]
    t.append("const HandlerFn kObjectHandlers[448] = {")
    for i in range(1, 449):
        t.append("\t%s," % ("wrap_%s" % ("objh_%03d" % i) if "objh_%03d" % i in generated else "nullptr"))
    t.append("};")
    t.append("")
    exits = sorted(n for n in generated if n.startswith("exit_fn_"))
    t.append("const HandlerFn kExitFunctions[%d] = {" % len(exits))
    for n in exits:
        t.append("\twrap_%s," % n)
    t.append("};")
    ev = sorted(n for n in generated if n.startswith("event_fn_"))
    t.append("")
    t.append("const HandlerFn kEventFunctions[%d] = {" % len(ev))
    for n in ev:
        t.append("\twrap_%s," % n)
    t.append("};")
    t.append("")
    t.append("const VerbHandler kVerbHandlers[%d] = {" % len(wh))
    for c, f in wh:
        t.append("\t{%s, wrap_%s}," % (c, f))
