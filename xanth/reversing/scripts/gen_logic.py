"""
Writes the game logic of Companions of Xanth as C++ (src/xanth/logic/*.cpp) from xanth.asm with the structured decompiler (decomp*.py).

    python gen_logic.py [--out DIR] [function ...]

Every object handler (objh_NNN), exit function, event function, conversation callback / text and default verb handler becomes one C++ function
`int name(Game &g, int arg0 ...)`; engine functions become members of Game, saved variables are members of g.state.v (Vars), the other globals are
members of g.rt (Runtime).  The text of the game is not in the output: messages are ids, MSG(block, index).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.argv, _argv = [sys.argv[0]], sys.argv
import decomp_gen as G
from decomp_emit import function_text, render_function
import decomp_out
from decomp_out import Names
sys.argv = _argv

NL = chr(10)
TAB = chr(9)
BS = chr(92)
SRC = os.path.abspath(os.path.join(HERE, "..", "..", "src"))
FAMILY = re.compile(r"^(objh_\d+|exit_fn_\d+|event_fn_\d+|conv_cb_\d+|conv_text_\d+|cmd[A-Z]\w*)$")
HDR = "// generated by reversing/scripts/gen_logic.py from the original program - do not edit. No game text: messages are ids."


def load_vars():
    """members of Xanth::Vars (the saved variables) with their C++ types"""
    out = {}
    for line in open(os.path.join(SRC, "xanth", "tables", "vars.h"), encoding="utf-8"):
        m = re.match(r"^\s+(uint8|uint16)\s+(\w+)(\[(\d+)\])?;", line)
        if m:
            out[m.group(2)] = (m.group(1), int(m.group(4)) if m.group(4) else 0)
    return out


class LogicNames(Names):
    def __init__(self, ctx, vars_):
        self.ctx = ctx
        self.vars = vars_
        self.rt = {}            # runtime globals: name -> max access size
        self.calls = {}         # engine function -> max argument count
        self.estr = {}          # program text -> index
        self.cur = None

    def glob(self, name, disp, size):
        name = self.ident(name)
        if name in self.vars:
            ty, n = self.vars[name]
            base = "v." + name
            if n:
                return base + "[%d]" % disp
            if disp:
                return "v.%s_hi" % name
            if size == 1 and ty == "uint16":
                return "(v.%s & 0xFF)" % name
            return base
        key = name + ("_hi" if disp else "")
        self.rt[key] = max(self.rt.get(key, 0), size or 2)
        return "rt." + key

    def loc(self, func, name, disp, size):
        m = re.match(r"^bp([+-]\d+)$", name)
        if m:
            off = int(m.group(1))
            name = "var_%X" % -off if off < 0 else "arg_%X" % (off - 6)
        n = {"arg_0": "arg0", "arg_2": "arg1", "arg_4": "arg2", "arg_6": "arg3", "arg_8": "arg4"}.get(name, name)
        n = re.sub(r"^var_", "v", n)
        if disp:
            return "%s_hi" % n
        return n

    def call(self, tgt, args):
        n = Names.func(self, tgt)
        if FAMILY.match(n):
            return "%s(%s)" % (n, ", ".join(["g"] + args))
        self.calls[n] = max(self.calls.get(n, 0), len(args))
        return "g.%s(%s)" % (n, ", ".join(args))

    def header(self, name, params):
        return "int %s(%s)" % (Names.func(self, name), ", ".join(["Game &g"] + ["int " + p for p in params]))

    def prolog(self):
        return ["Vars &v = g.state.v;", "Runtime &rt = g.rt;"]

    def kstring(self, off):
        t = self.ctx.dseg_string(off)
        if t is None:
            return "DSEG(0x%X)" % off
        if t not in self.estr:
            self.estr[t] = len(self.estr)
        return "ES(%d)" % self.estr[t]

    def msg(self, block, index):
        return "MSG(%d, %d)" % (block, index)

    def addr(self, sym):
        if sym in self.ctx.strings:
            return self.string(sym)
        if sym in self.ctx.procs:
            return "FN(%s)" % Names.func(self, sym)
        return "&rt." + self.ident(sym)

    def string(self, sym):
        """text that is part of the program (not of the message file) is kept out of the generated source: ES(n) is an index into engine_strings.inc"""
        t = self.ctx.strings.get(sym)
        if t is None:
            return "ES_UNKNOWN(%s)" % self.ident(sym)
        if t not in self.estr:
            self.estr[t] = len(self.estr)
        return "ES(%d)" % self.estr[t]


def argc(ctx, name):
    return sum(1 for k in ctx.locs.get(name, {}) if k.startswith("arg_"))


def write(path, text):
    with open(path, "w", encoding="utf-8", newline=NL) as fh:
        fh.write(text)


def main():
    args = sys.argv[1:]
    out_dir = os.path.join(SRC, "xanth", "logic")
    if "--out" in args:
        i = args.index("--out")
        out_dir = args[i + 1]
        del args[i:i + 2]
    ctx = G.Ctx()
    names = LogicNames(ctx, load_vars())
    todo = args or sorted(n for n in ctx.procs if FAMILY.match(n))
    os.makedirs(out_dir, exist_ok=True)
    ok, bad, chunks = [], {}, {}
    for n in todo:
        try:
            names.cur = n
            t = function_text(ctx, n, names)
        except Exception as e:
            bad[n] = str(e)[:100]
            continue
        ok.append(n)
        chunks.setdefault("cmd" if n.startswith("cmd") else re.sub(r"_?\d+$", "", n), []).append(t)
    print(len(ok), "functions,", len(bad), "failed")
    if args:
        for fam, ts in chunks.items():
            print(NL.join(ts))
        for n, e in bad.items():
            print("FAILED", n, e)
        return
    for fam, ts in chunks.items():
        step = 80 if fam == "objh" else 1000
        for k in range(0, len(ts), step):
            fn = "%s%s.cpp" % (fam, "_%02d" % (k // step) if len(ts) > step else "")
            body = (NL + NL).join(ts[k:k + step])
            write(os.path.join(out_dir, fn), HDR + NL + '#include "xanth/logic/logic.h"' + NL + NL + "namespace Xanth {" + NL + NL + body + NL + NL + "} // namespace Xanth" + NL)
    decl = [HDR]
    for n in sorted(todo):
        decl.append("int %s(Game &g%s);%s" % (n, "".join(", int a%d" % i for i in range(argc(ctx, n))), "  // not decompiled" if n in bad else ""))
    write(os.path.join(out_dir, "functions.inc"), NL.join(decl) + NL)
    write(os.path.join(out_dir, "runtime_vars.inc"), HDR + NL + "".join("%s %s;%s" % ("uint8" if sz == 1 else "uint16", n, NL) for n, sz in sorted(names.rt.items())))
    write(os.path.join(out_dir, "engine_calls.txt"), "".join("%s%s%d%s" % (n, TAB, c, NL) for n, c in sorted(names.calls.items())))
    lines = ["// generated by reversing/scripts/gen_logic.py - the text of the original program that the logic prints; local only, not committed"]
    for t, i in sorted(names.estr.items(), key=lambda kv: kv[1]):
        lines.append("/* %d */ %s," % (i, '"' + t.replace(BS, BS + BS).replace('"', BS + '"') + '"'))
    write(os.path.join(out_dir, "engine_strings.inc"), NL.join(lines) + NL)
    write(os.path.join(out_dir, "failed.txt"), "".join("%s%s%s%s" % (n, TAB, e, NL) for n, e in sorted(bad.items())))


if __name__ == "__main__":
    main()
