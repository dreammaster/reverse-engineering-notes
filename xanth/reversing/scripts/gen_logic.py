"""
Writes the game logic of Companions of Xanth as C++ (src/xanth/logic/*.cpp) from xanth.asm with the structured decompiler (decomp*.py).

    python gen_logic.py [--out DIR] [function ...]

Every object handler (objh_NNN), exit function, event function, conversation callback / text and default verb handler becomes one C++ function
`int name(Game &g, int arg0 ...)`; so do the engine routines that are game logic and not drawing (ENGINE_LOGIC).  The routines of the original that Game
implements by hand (HAND) are members of Game, every other routine it calls is reached through Game::other().  Saved variables are members of g.state.v
(Vars), the other globals are members of g.rt (Runtime).  The text of the game is not in the output: messages are ids, MSG(block, index); text that lives
in the executable's data segment goes to a local table (engine_strings.inc, not committed).
"""
