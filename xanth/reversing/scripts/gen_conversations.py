"""
gen_conversations.py: writes src/xanth/logic/conversations.cpp (the compiled-in conversation graph of the original: 1,036 simple lines, 400 menus with 1,300 options, the callbacks
and the text functions of the lines that build their text) from analysis/xanth_conversations.json (dump_conversations.py, structure and message ids only, no game text).
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.abspath(os.path.join(HERE, "..", "..", "src"))
NL = chr(10)
TAB = chr(9)


def entry(o, enabled):
    fn = "nullptr"
    msg = 0
    if "msg" in o:
        msg = 0xF0000000 | (o["msg"][0] << 16) | o["msg"][1]
    else:
        fn = o["name"]
    return "{0x%08X, %s, 0x%04X, %d}" % (msg, fn, o["next"], enabled)


def main():
    c = json.load(open(os.path.join(HERE, "..", "analysis", "xanth_conversations.json")))
    simple, menus = c["simple"], c["menus"]
    total = sum(len(m["options"]) for m in menus)
    opts = [None] * total
    for m in menus:
        for j, o in enumerate(m["options"]):
            assert opts[m["first"] + j] is None
            opts[m["first"] + j] = o
    assert all(o is not None for o in opts)
    texts = sorted({o["name"] for o in simple + opts if "name" in o})
    cbs = sorted({m["callback"]["name"] for m in menus if "callback" in m})
    t = ["// generated by reversing/scripts/gen_conversations.py from the original program - do not edit. No game text: messages are ids.",
         '#include "xanth/logic/logic.h"', "", "namespace Xanth {", ""]
    # the callbacks take 0 to 2 of (menu id, option number): wrappers with the common signature
    decl = open(os.path.join(SRC, "xanth", "logic", "functions.inc"), encoding="utf-8").read()
    for cb in cbs:
        m = re.search(r"int %s\(Game &g((?:, Word \w+)*)\);" % cb, decl)
        k = m.group(1).count("Word") if m else 2
        t.append("static int cb_%s(Game &g, Word convId, Word option) { (void)convId; (void)option; return %s(g%s); }" % (cb, cb, ", convId, option"[:[0, 8, 18][k]] if k else ""))
    t.append("")
    t.append("const ConvEntry kConvLines[%d] = {" % len(simple))
    for o in simple:
        t.append(TAB + entry(o, o["flag"]) + ",")
    t.append("};")
    t.append("")
    t.append("const ConvEntry kConvOptions[%d] = {" % total)
    for o in opts:
        t.append(TAB + entry(o, o["flag"]) + ",")
    t.append("};")
    t.append("")
    t.append("const ConvMenu kConvMenus[%d] = {" % len(menus))
    for m in menus:
        cb = "cb_" + m["callback"]["name"] if "callback" in m else "nullptr"
        t.append("%s{%d, %d, %d, %d, %s}," % (TAB, m["flag"], m["b1"], m["first"], len(m["options"]), cb))
    t.append("};")
    t.append("")
    t.append("const unsigned kConvLineCount = %d, kConvOptionCount = %d, kConvMenuCount = %d;" % (len(simple), total, len(menus)))
    t.append("")
    t.append("} // namespace Xanth")
    with open(os.path.join(SRC, "xanth", "logic", "conversations.cpp"), "w", encoding="utf-8", newline=NL) as f:
        f.write(NL.join(t) + NL)
    print("lines", len(simple), "options", total, "menus", len(menus), "text functions", len(texts), "callbacks", len(cbs))


main()
